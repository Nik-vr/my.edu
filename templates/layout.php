<?php

declare(strict_types=1);

/**
 * Общий каркас страницы: выбирает оболочку и вставляет в неё содержимое.
 *
 * Самой разметки здесь намеренно нет: их две, и они разные по устройству.
 *
 *   _shell_panel   новый стиль: тёмная шапка, меню слева, карточки.
 *                  Всё, что человек видит после входа.
 *
 *   _shell_public  страницы вне панели: вход, регистрация, восстановление
 *                  пароля. Узкая колонка без меню.
 *
 * Граница проходит по входу, а не по разделу: человек либо вошёл в систему,
 * либо ещё нет. Вход, регистрация и восстановление пароля — снаружи, у них
 * нет ни пользователя, ни меню; всё остальное — кабинет.
 *
 * Меню при этом есть не у всех: у ученика и наблюдателя нет ни одного права
 * в панели, и пустая тёмная колонка слева выглядела бы поломкой. Поэтому
 * сам блок меню рисуется, только когда в нём есть что рисовать, — см.
 * _shell_panel.php.
 *
 * Текущий пользователь приходит из ядра (оно кладёт currentUser в общий
 * контекст), поэтому шаблон не обязан знать, откуда он взялся.
 *
 * @var \MyEdu\Core\View $view
 * @var string $content
 * @var \MyEdu\Auth\User|\MyEdu\Auth\Student|null $currentUser
 * @var string $fontSize
 * @var string $theme личная тема из профиля: dark или light
 * @var string|null $appName
 * @var string $currentPath
 * @var list<array{title:string, items:list<array<string,mixed>>}> $panelNav
 */
$appName = $appName ?? 'Система контроля знаний';

/*
 * Значения по умолчанию. Шаблон объявлен с strict_types, и необъявленная
 * переменная привела бы к TypeError, то есть к 500 там, где человек просто
 * не пришёл по нужному адресу. Лучше неверная разметка, чем ошибка сервера.
 */
$currentPath = $currentPath ?? '/';
$panelNav = $panelNav ?? [];

/*
 * Тема и состояние меню — с умолчаниями по той же причине, что и путь:
 * страница ошибки рисуется мимо dispatch, и при отказе до кладки контекста в
 * шаблоне оказалась бы необъявленная переменная. Умолчания совпадают с
 * разметкой оболочки: тёмная тема и развёрнутое меню.
 */
$theme = $theme ?? \MyEdu\Auth\User::THEME_DARK;
$sidebarRail = $sidebarRail ?? false;

/*
 * Состояния разделов меню: пустое по умолчанию означает «ничего не свёрнуто
 * по личному выбору», и группам остаётся их дефолт из Kernel. Пустой массив
 * нужен только для страницы ошибки, нарисованной мимо dispatch.
 */
$navClosed = $navClosed ?? [];

/*
 * Размер шрифта по умолчанию — нормальный.
 *
 * В общей контекст его кладёт ядро, но страница ошибки рисуется мимо
 * dispatch, и при отказе до кладки контекста в шаблоне оказалась бы пустая
 * переменная. Собственного выбора у гостя нет, и нормальный размер — ровно
 * то, что он увидит: страница без `data-font-size` показывает систему как
 * задумано.
 */
$fontSize = $fontSize ?? \MyEdu\Auth\User::FONT_NORMAL;

/*
 * Новый стиль — всему, кто вошёл. Гостю остаётся старая вёрстка: она и
 * нужна на странице входа, которая по определению вне панели.
 */
$inPanel = $currentUser !== null;

require __DIR__ . '/' . ($inPanel ? '_shell_panel.php' : '_shell_public.php');
