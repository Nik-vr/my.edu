<?php

declare(strict_types=1);

/**
 * Заголовок страницы — один компонент на всех страницах панели.
 *
 * Ожидает:
 *   $view, $title — заголовок страницы; $subtitle — пояснение под ним, если оно
 *   есть; $actions — готовая разметка кнопок справа от заголовка, если они
 *   нужны именно здесь.
 *
 * Заголовок нужен один и тот же на всех страницах — и по виду, и по месту.
 * Раньше он то стоял над карточкой, то прятался внутрь неё, то был заголовком
 * первого уровня, то второго: при переходе с одной страницы на другую
 * заголовок то поднимался над содержимым, то проваливался внутрь карточки, и
 * взгляд начинал каждый раз заново. Разметка страницы оказывалась в четырёх
 * видах.
 *
 * Подзаголовок — часть заголовка, а не текст внутри карточки: он объясняет, что
 * страница, и должен стоять под названием, а не над таблицей.
 *
 * $titleRaw — заголовок готовой разметкой, когда в названии есть значки
 * (например «владелец» рядом с именем). Всё, что приходит таким путём, должно
 * быть собрано самим шаблоном с экранированием: компонент ничего не чинит.
 *
 * @var \MyEdu\Core\View $view
 * @var string $title
 * @var string $titleRaw
 * @var string $subtitle
 * @var string $actions
 */
$view = $view ?? null;
$title = $title ?? '';
$titleRaw = $titleRaw ?? '';
$subtitle = $subtitle ?? '';
$actions = $actions ?? '';
?>
<div class="page-header">
 <h1 class="page-title">
 <?php if ($titleRaw !== ''): ?>
 <?= $view->raw($titleRaw) ?>
 <?php else: ?>
 <?= $view->e($title) ?>
 <?php endif; ?>
 </h1>

 <?php if ($subtitle !== ''): ?>
 <p class="muted"><?= $view->raw($subtitle) ?></p>
 <?php endif; ?>

 <?php if ($actions !== ''): ?>
 <div class="page-actions"><?= $view->raw($actions) ?></div>
 <?php endif; ?>
</div>