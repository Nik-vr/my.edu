<?php

declare(strict_types=1);

/**
 * Строки шкалы оценок.
 *
 * Отдельным файлом, потому что рисуются дважды: у режима «по проценту» своя
 * строка с одной границей, у режима «по баллам» — своя, с двумя. Копия в
 * обоих местах разошлась бы при первой правке, а разошлась бы тихо: у
 * процентов появилась бы вторая граница, у баллов — подпись в процентах.
 *
 * Вид строки собран так, чтобы её не приходилось читать: слева граница, в
 * середине цвет, справа сама оценка крупно и той же краской. Раньше оценка
 * стояла узкой цифрой слева от полей, а под словами жила отдельная подпись;
 * между «от 85 процентов» и тем, что это пятёрка, приходилось переводить
 * взгляд через всю строку. Теперь стрелка и цифра рядом с границей, и цвет
 * один и тот же у оценки и у её подложки в списке выбора.
 *
 * Подпись словами заменена цветом: в журнале и на странице результата
 * ученик видит оценку той же краской, какой автор выбрал здесь.
 *
 * Ожидает:
 * $view, $scaleRows, $scaleMode, $badFrom, $badTo, $total
 *
 * @var \MyEdu\Core\View $view
 * @var array<int,array{from:?float,to:?float,color:string}> $scaleRows границы этого режима
 * @var string $scaleMode percent или score
 * @var list<int> $badFrom оценки с неверной нижней границей
 * @var list<int> $badTo оценки с неверной верхней границей
 * @var float $total сумма цен заданий работы — для пересчёта процентов в баллы
 */

use MyEdu\Grading\GradeScaleValidator;

$byScore = $scaleMode === 'score';

/*
 * Шаг границ в баллах считается по сумме цен, а в процентах он всегда целый.
 *
 * Раньше здесь стояло `0.5` на все случаи, и при сумме, которая не делилась на
 * два, поле отвергало границы, которые сервер подставил в него сам: браузер и
 * проверка браузера считали число не кратным шагу и отвечали «проверьте поля»
 * на полностью заполненной форме.
 */
$boundaryStep = $byScore ? GradeScaleValidator::scoreGrid($total) : '1';

/*
 * У каждого набора свои имена полей: percent_min[] и score_min[].
 *
 * Наборы уходят с формой оба, иначе переключение режима стирало бы то, что
 * уже набрано в другом. Общие имена означали бы восемь чисел в одном списке,
 * и серверу пришлось бы угадывать, чьи это строки, — по порядку полей в
 * разметке, то есть по тому, как сегодня выглядит шаблон. Свои имена делают
 * разбор однозначным: сервер берёт те границы, имя которых совпадает с
 * отмеченным режимом, и не смотрит на остальные.
 *
 * Цвет — одно поле на оба режима: он не зависит от того, чем считают, и
 * две копии по одной подписи в каждом наборе разошлись бы при первой правке
 * так же, как разошлись бы границы.
 */

/*
 * Оценка не поле, а подпись. Принимать её от автора было бы способом
 * получить шкалу «3, 4, 5, 8, 12», которую не объяснишь ни ученику, ни
 * родителю.
 */
$lastGrade = GradeScaleValidator::GRADES[count(GradeScaleValidator::GRADES) - 1];

/*
 * Сколько баллов соответствует проценту.
 *
 * Подсказка отвечает на вопрос, который иначе остаётся без ответа: «75%» —
 * это сколько именно баллов? Автор задаёт границы в процентах, а ученик
 * работает с баллами, и без пересчёта проценты выглядят оторванными от работы.
 *
 * Округление до половины балла — тем же, что и в сведении результата, иначе
 * подсказка обещала бы 11,05 балла там, где на странице результата стоит
 * 11, и человек сверял бы два разных числа об одном и том же пороге.
 *
 * Полбалла, а не сотые: автор задаёт границу в процентах и вкладывает в неё
 * «проценты, соответствующие половине балла», то есть целым числом баллов.
 * Число с двумя знаками после запятой выглядело бы как расчёт машины и
 * обесценивало бы подсказку, ради которой она и написана.
 */
$pointsFor = static function (?float $percent) use ($total): ?float {
    if ($percent === null || $total <= 0.0) {
        return null;
    }

    return round($total * $percent / 100.0 * 2) / 2;
};

$pointsText = static function (?float $points) use ($total): string {
    if ($points === null) {
        return '';
    }

    return GradeScaleValidator::formatNumber($points) . ' из ' . GradeScaleValidator::formatNumber($total);
};
?>

<?php foreach (GradeScaleValidator::GRADES as $grade) {
    $row = $scaleRows[$grade] ?? ['from' => null, 'to' => null, 'color' => null];
    $color = GradeScaleValidator::normalizeColor($row['color'] ?? null, $grade);
    $fromBad = in_array($grade, $badFrom, true);
    $toBad = $byScore && in_array($grade, $badTo, true);
    /*
     * У двойки нижней границы нет: диапазон тянется от нуля, и спрашивать
     * число там не о чем. Подсказка стоит под полем, а не над ним — иначе
     * строка у двойки была бы на два поля выше остальных и шкала разрезалась
     * бы неровно.
     *
     * Но пустое поле — только у свежей формы. Если автор вписал туда число и
     * сервер его отверг, поле показывает именно это число: пустое поле рядом с
     * объяснением «должна быть 0» не сказало бы, что было введено, и человек
     * набирал бы заново то, что уже стёрли за него.
     */
    $isBottom = $grade === $lastGrade;
    $bottomKeepsValue = $isBottom && $row['from'] !== null && (float) $row['from'] !== 0.0;

    /*
     * Поле у двойки скрыто, но при отвергнутом значении возвращается на место.
     *
     * Иначе автор получил бы «должна быть 0» и строку без единого помеченного
     * поля: исправлять было бы нечего, а введённое число осталось бы в
     * скрытом поле и уехало обратно при следующей отправке. На ошибочную
     * строку та же разметка, что и у остальных оценок, — с классом ошибки и
     * aria-invalid.
     */
    $bottomFieldShown = $isBottom && $fromBad;
?>
<div class="scale-row<?= $fromBad ? ' scale-row--error' : '' ?>" data-grade="<?= $view->e($grade) ?>">
  <div class="scale-row__bounds">
   <?php if ($isBottom && ! $bottomFieldShown): ?>
    <?php /*
     * У двойки вместо поля — надпись «Считается автоматически».
     *
     * Поля было две беды. Первая — в него вводили 0 и считали это настройкой:
     * диапазон двойки тянется от нуля до «минус единица» от порога тройки, и
     * спрашивать число там не о чем. Вторая, и та, что видна сразу: строка без
     * поля оказывалась ниже остальных, цвет со стрелкой и цифра уезжали вниз,
     * и четыре строки шкалы снова читались по наклонной. Надпись занимает
     * ровно место поля — подпись сверху и рамка той же высоты, — и ряд
     * встаёт на одну линию с остальными, а объяснять «откуда ноль» всё равно
     * нужно было.
     *
     * Скрытое поле с тем же именем обязательно и в этом случае: границы
     * читаются по индексу массива, и без него у двойки и всех выше сдвинулась
     * бы нумерация — каждая оценка получила бы число соседней.
     *
     * Поле «Максимальное значение» в балловом наборе у двойки остаётся:
     * верхняя граница там и вводится руками.
     */
    ?>
    <input type="hidden" name="<?= $scaleMode ?>_min[]"
    value="<?= $view->e($bottomKeepsValue ? $row['from'] : 0) ?>">
    <div class="scale-field scale-field--auto">
     <span class="form-label scale-field__label">Минимальное значение</span>
     <span class="scale-auto">Считается автоматически</span>
    </div>
   <?php else: ?>
    <label class="scale-field<?= $fromBad ? ' field--error' : '' ?>">
     <?php /*
      Подпись без единицы измерения: «Минимальное значение, баллы» не помещалась
      в одну строку, переносилась и опускала своё поле ниже соседнего — четыре
      строки шкалы выстраивались «лесенкой», и числа приходилось сравнивать на
      глаз. Единица названа один раз в подписи над набором.
      */ ?>
     <span class="form-label scale-field__label">Минимальное значение</span>
     <input type="number" name="<?= $scaleMode ?>_min[]" min="0" step="<?= $view->e($boundaryStep) ?>"
     <?= $byScore ? '' : 'max="100"' ?>
     value="<?= $view->e($row['from']) ?>"
     <?= $fromBad ? 'aria-invalid="true"' : '' ?>
     <?php if (!$byScore): ?>
     data-hint-template="__PERCENT__% — __POINTS__ из __TOTAL__ баллов"
     data-total="<?= $view->e($total > 0 ? GradeScaleValidator::formatNumber($total) : '') ?>"
     data-total-value="<?= $view->e($total) ?>"
     <?php endif; ?>>

     <?php /*
      Подсказка о баллах под полем, а не соседним элементом строки: будь она
      рядом с границей, занимала бы место в ряду и сдвинула цвет, стрелку и
      оценку вправо относительно остальных строк.
      */ ?>
     <?php if (!$byScore): ?>
     <span class="scale-row__points" data-scale-points><?=
      $view->e($pointsText($pointsFor($row['from'] === null ? null : (float) $row['from'])))
     ?></span>
     <?php endif; ?>
    </label>
   <?php endif; ?>

   <?php if ($byScore): ?>
   <label class="scale-field<?= $toBad ? ' field--error' : '' ?>">
    <span class="form-label scale-field__label">Максимальное значение</span>
    <input type="number" name="<?= $scaleMode ?>_max[]" min="0" step="<?= $view->e($boundaryStep) ?>"
    value="<?= $view->e($row['to']) ?>"
    <?= $toBad ? 'aria-invalid="true"' : '' ?>>
   </label>
   <?php endif; ?>
  </div>

 <label class="scale-field scale-field--color">
  <span class="form-label">Цвет</span>
  <?php /*
   * Нативное поле выбора цвета — решение владельца от 24.10.2026 (задача 4).
   *
   * По нажатию браузер показывает стандартное окно, где лежат и привычные
   * четыре краски, и любая другая: прежняя палитра из четырёх кнопок
   * закрывала выбор предустановленным набором, а автор мог захотеть
   * оранжевый «поближе к жёлтому».
   *
   * Значение — всегда HEX: название из палитры переводится по `colorHex()`,
   * свой цвет проходит как есть. Поле без подписи для чтения с экрана —
   * просто квадрат, поэтому у него есть имя с номером оценки.
   */ ?>
  <input type="color" name="color[]"
   value="<?= $view->e(GradeScaleValidator::colorHex($color)) ?>"
   class="scale-color__input"
   title="Цвет оценки <?= $view->e($grade) ?>"
   aria-label="Цвет оценки <?= $view->e($grade) ?>">
 </label>

 <span class="scale-row__arrow" aria-hidden="true">→</span>

 <span class="scale-row__grade<?php
 /*
  * Краска строки в форме: четыре палитры дают готовый класс, а свой цвет
  * класса не имеет и передаётся атрибутом — его применяет скрипт
  * `grade-color.js`. Класс вида `--#2fb344` не сделал бы ничего, кроме
  * сломанного имени.
  */
 ?><?= GradeScaleValidator::isPaletteColor($color)
     ? ' scale-row__grade--' . $view->e($color)
     : '' ?>"
 <?= GradeScaleValidator::isPaletteColor($color)
     ? ''
     : 'data-grade-color="' . $view->e($color) . '"' ?>>
  <?= $view->e($grade) ?>
 </span>
</div>
<?php }