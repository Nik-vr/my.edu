<?php

declare(strict_types=1);

/**
 * Выбор личного размера шрифта: мелкий, нормальный, крупный.
 *
 * Общая часть для карточки сотрудника и карточки ученика. Форма одна и та же
 * у обоих, разнятся они только адресом страницы, на которой стоят, — поэтому
 * держать копию разметки в двух шаблонах значило бы править её в двух местах
 * и рано или поздно разнести.
 *
 * Переключение без JavaScript: человек отмечает и нажимает «Сохранить»,
 * страница перезагружается уже в новом размере. Скрипт здесь не нужен и не
 * добавлялся — оболочка страницы рисует атрибут `data-font-size` на <html>
 * на сервере, и размер известен до того, как браузер увидит страницу.
 *
 * Ожидает в области видимости:
 * $view, $ui, $fontSize
 *
 * @var \MyEdu\Core\View $view
 * @var \MyEdu\Ui\Ui $ui
 * @var string $fontSize
 */

use MyEdu\Auth\User;

/*
 * Подписи к размерам — слова, а не числа процентов.
 *
 * «−25%» потребовало бы от человека знать, от чего считать, а «мелкий»
 * говорит то же и без расчёта. Куда именно уходит каждая подпись — решает
 * CSS: здесь размер не задаётся и не подмешивается.
 */
$labels = [
    User::FONT_SMALL  => 'Мелкий',
    User::FONT_NORMAL => 'Нормальный',
    User::FONT_LARGE  => 'Крупный',
];

$options = '<div class="profile-font-size__choices">';

foreach (User::fontSizes() as $size) {
    $options .= $ui->radio('font_size', [
        'label'   => $labels[$size],
        'value'   => $size,
        'id'      => 'font-size-' . $size,
        'checked' => $fontSize === $size,
    ]);
}

$options .= '</div>';

/*
 * Кнопка отдельной строкой, а не в одном ряду с переключателями: три
 * переключателя и кнопка рядом выглядят как четыре равнозначных выбора, и
 * человек нажимает не туда.
 */
$options .= '<div class="profile-font-size__actions">'
    . '<button type="submit" class="btn btn-primary">Сохранить размер</button>'
    . '</div>';

echo $view->raw($ui->group(
    [
        'label' => 'Размер шрифта',
        'help'  => 'Влияет только на то, как система выглядит у вас. Остальным людям ваш выбор не мешает.',
    ],
    $options
));
