<?php

declare(strict_types=1);

/**
 * Выбор личной темы: тёмная, светлая.
 *
 * Общая часть для карточки сотрудника и карточки ученика — та же природа,
 * что у формы размера шрифта: свойство одно («так мне удобно смотреть»), а
 * страниц профиля две, и держать копию разметки в двух шаблонах значило бы
 * править её в двух местах и рано или поздно разнести.
 *
 * Переключение без JavaScript: человек отмечает и нажимает «Сохранить»,
 * страница перезагружается уже в выбранной теме — оболочка рисует атрибут
 * `data-theme` на сервере, читая выбор из профиля. Кнопка в шапке делает то
 * же самое, но без перезагрузки: адрес у неё тот же, `/profile/theme`.
 *
 * Ожидает в области видимости:
 * $view, $ui, $theme
 *
 * @var \MyEdu\Core\View $view
 * @var \MyEdu\Ui\Ui $ui
 * @var string $theme
 */

use MyEdu\Auth\User;

/*
 * Подписи — слова, а не атрибуты разметки: человек выбирает «светлую», а
 * не `data-theme="light"`. Приведение значения идёт здесь же: если тема
 * в базе чем-то испорчена, форма покажет умолчание, а не пустой выбор.
 */
$theme = User::themeOf($theme ?? null);

$labels = [
    User::THEME_DARK  => 'Тёмная',
    User::THEME_LIGHT => 'Светлая',
];

$choices = '<div class="profile-theme__choices">';

foreach (User::themes() as $one) {
    $choices .= $ui->radio('theme', [
        'label'   => $labels[$one],
        'value'   => $one,
        'id'      => 'theme-' . $one,
        'checked' => $theme === $one,
    ]);
}

$choices .= '</div>';

/*
 * Кнопка отдельной строкой — тем же приёмом, что в форме размера шрифта:
 * два выбора и кнопка в одном ряду выглядят как четыре равнозначных
 * выбора, и человек нажимает не туда.
 */
$choices .= '<div class="profile-theme__actions">'
    . '<button type="submit" class="btn btn-primary">Сохранить тему</button>'
    . '</div>';

echo $view->raw($ui->group(
    [
        'label' => 'Тема оформления',
        'help'  => 'Влияет только на то, как система выглядит у вас.',
    ],
    $choices
));
