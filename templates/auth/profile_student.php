 * Это не сведение о нём и не пароль, а привычка чтения, и в системе, где
 * счётчики и подписи набраны мелко, выбор размера должен быть доступен
 * каждому, а не только сотрудникам.
 *
 * Разметка шаблона gentelella: .card / .card-body и .facts как на странице
 * сотрудника, чтобы два вида «моих данных» читались как один сайт.
