<?php

declare(strict_types=1);

namespace MyEdu\Http\Routes;

use MyEdu\Core\Router;

/**
 * Один файл карты маршрутов.
 *
 * Карта разделена по частям сайта, а не по контроллерам: в файле лежат все
 * адреса одного смыслового куска — «вход», «работы», «панель», «классы». Так
 * видно, что адрес открывает и кому он доступен, не перелистывая ядро.
 *
 * Порядок внутри файла значим и задаётся здесь же: `Router::match()` берёт
 * первое совпадение, поэтому литеральный адрес объявляется раньше адреса с
 * `{id}` — иначе «new» или «roles» разобралось бы как номер.
 *
 * Между файлами порядок не значим: у них разные префиксы, и ни один адрес из
 * одного файла не совпадает с адресом из другого. Проверять это пришлось бы
 * перебором, поэтому простое правило «файлы подключаются списком в `Kernel`»
 * дешевле проверки.
 */
interface RouteFile
{
    /**
     * Дописать свою часть карты в роутер.
     *
     * `$router` общий на все файлы: так сохраняется сквозной порядок, а каждый
     * файл остаётся куском, который можно прочитать целиком.
     */
    public static function register(Router $router, Controllers $controllers): void;
}