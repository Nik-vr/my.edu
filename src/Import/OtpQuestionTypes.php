<?php

declare(strict_types=1);

namespace MyEdu\Import;

/**
 * Соответствие типов заданий OnlineTestPad типам этой системы.
 *
 * Тип задания лежит в поле `AnswerType`, а не в `QuestionType`: последнее у всех
 * вопросов равно 10 и ничего не различает. Перебор всех 26 значений взят из
 * перечисления самой офлайн-версии — иначе неизвестный тип выглядел бы как
 * «один вариант ответа», и в тесте молча появились бы задания с чужими
 * правильными ответами.
 *
 * Типы без соответствия не переносятся и попадают в отчёт: угадывать, во что
 * превратить «найди исключение», нельзя, а пропустить молча — значит учитель
 * узнает о пропаже только тогда, когда ученик дойдёт до этого задания.
 */
final class OtpQuestionTypes
{
    /**
     * Тип нашей системы для кода OnlineTestPad; null — перенести нечем.
     *
     * @var array<int,string>
     */
    private const TYPES = [
        // Один вариант: в том числе со шкалой оценки — сама шкала у нас есть
        // только у другого плагина, но правильный ответ переносится целиком.
        10 => 'single_choice',
        11 => 'single_choice',
        310 => 'single_choice',

        // Несколько вариантов.
        210 => 'multiple_choice',
        211 => 'multiple_choice',

        // Порядок: упорядочивание и сборка фразы из слов устроены одинаково —
        // правильный порядок лежит в ValueInt каждого элемента.
        510 => 'ordering',
        1110 => 'ordering',

        // Числовой ответ: и явное поле числа, и пропуск внутри текста.
        410 => 'numeric',
        450 => 'numeric',

        /*
         * Пропуск с описанием — тоже числовой ответ: ученик вводит число и,
         * если хочет, поясняет его словами. Числовая часть переносится целиком,
         * а пояснение отбрасывается: в системе у числового задания поля для
         * пояснения нет, и придумывать его значило бы заставлять ученика писать
         * текст, который никто не проверит.
         *
         * Раньше эти два типа были не перенесены вовсе, и задание уходило в
         * пропущенные с формулировкой «в системе нет задания "пропуск с
         * описанием"» — при том, что числовой ответ переносится прекрасно.
         * Расширенный вариант отличается только объёмом пояснения.
         */
        470 => 'numeric',
        475 => 'numeric',

        // Текстовый ответ.
        420 => 'text',
        430 => 'text',
        460 => 'text',

        // Соответствие двух колонок.
        610 => 'matching',
    ];

    /**
     * Название типа у OnlineTestPad — для отчёта о пропущенных заданиях.
     *
     * @var array<int,string>
     */
    private const TITLES = [
        10 => 'один вариант ответа',
        11 => 'один вариант ответа со шкалой',
        20 => 'один вариант в таблице',
        210 => 'несколько вариантов ответа',
        211 => 'несколько вариантов со шкалой',
        220 => 'несколько вариантов в таблице',
        310 => 'выбор из списка',
        320 => 'выбор из списка в таблице',
        410 => 'числовой ответ',
        420 => 'короткий текстовый ответ',
        430 => 'развёрнутый текстовый ответ',
        450 => 'пропуск с числом',
        460 => 'пропуск с текстом',
        470 => 'пропуск со списком',
        475 => 'пропуск со списком (расширенный)',
        510 => 'расставить по порядку',
        610 => 'соответствие',
        700 => 'найти исключение',
        800 => 'ползунок',
        900 => 'загрузка файла',
        910 => 'запись голоса',
        1100 => 'слово из букв',
        1110 => 'фраза из слов',
        1120 => 'найти в тексте',
        1121 => 'найти букву в тексте',
        1122 => 'найти слово в тексте',
        1123 => 'найти в тексте (свой вариант)',
    ];

    /** Наш тип по коду OnlineTestPad; null — перенести нечем. */
    public static function type(int $answerType): ?string
    {
        return self::TYPES[$answerType] ?? null;
    }

    /**
     * Человеческое название типа OnlineTestPad.
     *
     * Код не из таблицы всё равно называется по-русски: иначе в отчёте будет
     * «AnswerType 4799», и по этому ничего не понять.
     */
    public static function title(int $answerType): string
    {
        return self::TITLES[$answerType] ?? ('неизвестный тип ' . $answerType);
    }

    /** Типы, которые эта система переносит. Документация и отчёт. */
    public static function supported(): array
    {
        return array_keys(self::TYPES);
    }
}