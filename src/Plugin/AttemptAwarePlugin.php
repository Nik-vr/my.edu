<?php

declare(strict_types=1);

namespace MyEdu\Plugin;

/**
 * Плагину, хранящему данные по попытке работы, сообщить об её удалении.
 *
 * Отдельный интерфейс, а не метод в AssessmentPlugin, по той же причине, что
 * и у ClassAwarePlugin: контракт задания плагин реализует всегда, а свои
 * таблицы прохождений заводит не каждый. Обязательный метод в AssessmentPlugin
 * заставил бы большинство плагинов писать пустое тело.
 *
 * Зачем это нужно. Ядро удаляет попытку целиком только в одном случае —
 * тестовое прохождение под виртуальным учеником: проба живёт до закрытия
 * вкладки и в статистику не попадает. Результаты позиций уходят каскадом по
 * внешнему ключу, а таблицы прохождений плагинов на попытку ядра не ссылаются
 * вовсе — номера хранятся числами, не внешними ключами (см. миграции
 * плагинов): без этого вызова каждая проба оставляла бы в базе плагина
 * мёртвые строки ответов.
 *
 * Когда вызывается. ДО удаления строки попытки: плагин ещё видит номер и
 * убирает свои строки по нему. Отказ плагина не останавливает удаление
 * попытки — она обязана исчезнуть, — но записывается в журнал плагинов.
 */
interface AttemptAwarePlugin
{
    /**
     * Попытка работы удаляется: убрать свои строки, привязанные к её номеру.
     *
     * Ответы и прохождения, ссылающиеся на позицию или задание по отдельности,
     * здесь не трогаются: их убирает deleteItem()/deleteTask(), когда позиция
     * или задание покидают работу. Здесь речь только о данных самой попытки.
     */
    public function deleteAttemptData(int $assignmentAttemptId): void;
}
