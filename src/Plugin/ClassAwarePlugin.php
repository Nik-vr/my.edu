<?php

declare(strict_types=1);

namespace MyEdu\Plugin;

/**
 * Плагину, которому важен класс, сообщить об его удалении.
 *
 * Отдельный интерфейс, а не метод в AssessmentPlugin: контракт задания плагин
 * реализует всегда, а класс для большинства плагинов — посторонняя сущность.
 * Обязательный метод в AssessmentPlugin заставил бы каждый плагин писать
 * пустое тело и со временем забыл бы, зачем оно.
 *
 * Зачем это нужно. Удаление класса убирает и его учеников: теряются учётные
 * записи вместе с логинами, паролями и всеми попытками — не только по этому
 * классу, а вообще. Свои данные плагина (тесты, привязанные к классу) при
 * этом остаются: в таблице `tests` класс обнуляется, и тест живёт уже ни в чьём
 * классе. Ядро об этом знает, плагин — нет: он не получает ни отказа, ни
 * уведомления, и его данные остаются сиротами молча.
 *
 * Хук вызывается ПОСЛЕ удаления класса и учеников. Он ничего не может отменить
 * (удаление уже состоялось) и нужен для уборки: пометить свои записи как
 * отвязанные, снять привязку, записать в свой журнал, что класс больше не
 * существует.
 *
 * @phpstan-type ClassRemoval array{classId:int, className:string, studentIds:list<int>}
 */
interface ClassAwarePlugin
{
    /**
     * Класс удалён вместе со своими учениками.
     *
     * @param array{classId:int, className:string, studentIds:list<int>} $removal
     *
     * @return list<string> заметки для человека: что плагин убрал или оставил.
     *                      Пустой список означает «ничего особенного», и в
     *                      сообщении об удалении класса тогда не будет лишней
     *                      строки.
     */
    public function onClassRemoved(array $removal): array;
}