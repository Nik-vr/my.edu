<?php

declare(strict_types=1);

namespace MyEdu\Plugin;

/**
 * Плагин, чьи задания умеют переноситься между инсталляциями.
 *
 * Отдельный интерфейс, а не ещё два метода в общем контракте: перенос нужен не
 * всем и не всем сразу, а обязательный метод в контракте заставил бы каждый
 * новый плагин реализовывать выгрузку данных, о которых он ничего не знает.
 * Нет интерфейса — нет и переносимого задания, и это честнее, чем выгрузка,
 * которая молча приносит половину данных.
 *
 * Что именно переносится, решает плагин: у него свои таблицы и своя форма
 * задания. Ядро отдаёт и принимает непрозрачный массив и не заглядывает внутрь.
 */
interface PortablePlugin
{
    /**
     * Данные задания для переноса.
     *
     * @return array<string,mixed>|null null — задание перенести нельзя, и
     *                                     выгрузка это пропустит
     */
    public function exportTask(TaskRef $task): ?array;

    /**
     * Создать задание из данных переноса.
     *
     * Возвращается номер созданного задания: вид задания (`kind`) ядро знает и
     * само — он лежит рядом с данными в пакете, и собирать ссылку на задание
     * должен тот, кто владеет позициями работы.
     *
     * Ядро вызывает этот метод внутри транзакции и savepoint одного задания.
     * Запись плагина должна использовать переданное соединение приложения и не
     * фиксировать/закрывать внешнюю транзакцию вручную: при ошибке savepoint
     * откатит частично созданное задание, сохранив остальные импортируемые.
     *
     * @param array<string,mixed> $data       то, что вернул exportTask()
     * @param string              $kind       вид задания из пакета
     * @param int                 $authorId   автор на новом месте
     * @param int|null            $subjectId  предмет на новом месте, если работа с ним связана
     */
    public function importTask(array $data, string $kind, int $authorId, ?int $subjectId = null): int;
}
