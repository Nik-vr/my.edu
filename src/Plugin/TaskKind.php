<?php

declare(strict_types=1);

namespace MyEdu\Plugin;

/**
 * Вид задания, который предлагает плагин.
 *
 * Это то, что видит учитель в списке доступных заданий, и то, по чему ядро
 * группирует позиции работы в интерфейсе.
 *
 * Один плагин вправе предлагать несколько видов: «Тест» отдаёт по виду на
 * каждый тип вопроса, и учитель выбирает нужный, не заходя внутрь.
 */
final class TaskKind
{
    /** Задание приносит баллы: учитель задаёт максимум, плагин — долю от него. */
    public const SCORING_POINTS = 'points';

    /** Задание возвращает процент выполнения, максимум ядро не назначает. */
    public const SCORING_PERCENT = 'percent';

    public function __construct(
        public readonly string $slug,
        public readonly string $title,
        public readonly string $description = '',
        public readonly string $scoring = self::SCORING_POINTS
    ) {
    }

    /**
     * Назначает ли учитель максимум баллов этому виду задания.
     *
     * Разница видна в том, как видно работу ученику и как она сводится:
     * у балльного задания есть конкретная цена в баллах, у процентного её
     * считает плагин, и учитель задаёт только «сколько это весит в общей работе».
     *
     * Система проверки вправе объявить любой вид: проценты удобны там, где
     * правильных вариантов много и заранее известна доля, набранная верным
     * ответом.
     */
    public function usesPoints(): bool
    {
        return $this->scoring === self::SCORING_POINTS;
    }
}