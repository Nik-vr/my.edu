<?php

declare(strict_types=1);

namespace MyEdu\Plugin;

use MyEdu\Core\Request;
use MyEdu\Core\Response;

/**
 * Плагин системы оценивания.
 *
 * Контракт ядра. Список типов заданий, которые видит учитель, собирается из
 * подключённых плагинов, поэтому добавление новой системы оценивания не
 * требует правок в ядре: достаточно положить папку в plugins/ и включить
 * плагин в панели управления.
 *
 * Один плагин отвечает за один способ проверки знаний целиком: тест, игра,
 * тренажёр, квиз. Внутри него — свои типы заданий и своя схема хранения.
 *
 * Обязательное требование к любому плагину — начало условия задания для
 * списка работы: возвращается через taskPreview(). Подробности — у метода.
 *
 * Плагин — доверенный код: он выполняется в том же процессе и имеет полный
 * доступ к базе и файлам. Это осознанный выбор, а не недосмотр: игра с
 * собственным интерфейсом иначе не выразить через общий API.
 */
interface AssessmentPlugin
{
    /** Идентификатор из манифеста plugin.json. Латиница, цифры, дефис. */
    public function id(): string;

    /** Название для интерфейса учителя и списка плагинов. */
    public function name(): string;

    /** Версия плагина. Показывается в панели и пишется в журнал установки. */
    public function version(): string;

    /**
     * Что этот плагин умеет: список видов заданий для выбора учителем.
     *
     * Одна система оценивания может давать несколько видов: например, тест
     * с вопросами и тест с заданиями на перенос. Ядро ничего о них не знает.
     *
     * @return list<TaskKind>
     */
    public function taskKinds(): array;

    /**
     * Собственные маршруты плагина.
     *
     * Регистрируются под /plugin/<id>/… и нужны для экранов, которые ядро
     * не рисует: пошаговые задачи, AJAX-обмен для игр, загрузка файлов.
     *
     * Формат элемента: ['GET', '/result/{taskId}', 'resultAction'].
     *
     * @return list<array{0:string,1:string,2:string,3?:string}>
     */
    public function routes(): array;

    /**
     * Установка: применить собственные migrations/*.sql.
     *
     * Вызывается при первой установке и при смене версии плагина. DDL MySQL не откатывается
     * общей транзакцией; для файловых миграций используйте
     * PluginMigrationRunner, который сохраняет checkpoint каждого оператора.
     */
    public function install(): void;

    /**
     * Форма редактора задания без оболочки страницы.
     *
     * Нужна для встраивания: в редакторе работы задание правится на месте, и
     * переход на отдельную страницу уводил бы автора из списка, где видно
     * остальные позиции работы.
     *
     * Форма отправляется на адрес плагина и после сохранения возвращает
     * автора туда, откуда пришли. Возвращается HTML, а не Response: ядро
     * вставляет его в свою страницу.
     *
     * @return string готовый HTML формы
     */
    public function renderEditorFragment(EditorContext $context): string;

    /**
     * Экран задания для ученика внутри работы.
     *
     * Ядро отдаёт только то, что само знает: позицию работы, номер в
     * последовательности, попытку. Всё остальное плагин берёт сам.
     */
    public function renderTask(AttemptContext $context): Response;

    /**
     * Приём, проверка полей и сохранение ответа ученика.
     *
     * Вызывается на каждый переход между заданиями, поэтому ответ должен
     * сохраняться здесь же: иначе работа теряется при обновлении страницы.
     * Ядро проверяет CSRF до вызова метода; плагин проверяет формат и смысл
     * собственных полей ответа.
     */
    public function saveAnswer(AttemptContext $context, Request $request): void;

    /**
     * Проверка одного задания.
     *
     * Возвращает балл и, если у плагина есть собственные критерии оценивания,
     * оценку за это задание.
     */
    public function grade(AttemptContext $context): ItemGrade;

    /**
     * Разбор задания для страницы результата.
     *
     * Снимок разбора лежит в ItemGrade::snapshot — пересчитывать его при
     * показе нельзя, иначе правка вопроса изменила бы то, что ученик видел.
     */
    public function renderReview(AttemptContext $context, ItemGrade $grade): Response;

    /**
     * То, что ученик ответил, — для показа учителю при ручной проверке.
     *
     * Вызывается только там, где задание ждёт проверки учителем. Ответ нужно
     * показать целиком и в том виде, в каком он пришёл: проверять не видя
     * ответа бессмысленно.
     *
     * null означает «показать нечего»: задание без автопроверки вовсе не имеет
     * ответа в базе плагина, и это нормально.
     */
    public function renderSubmitted(AttemptContext $context): ?Response;

    /**
     * Короткий текст ответа ученика — для подсказок в таблицах журнала.
     *
     * Полный разбор в подсказке не нужен и стоит дорого: в таблице журнала
     * ответов десятки, и каждый показывается целиком. Поэтому ядро просит
     * именно строку — что ученик ответил, — а плагин берёт её из снимка
     * позиции, который и так сохранён рядом с результатом.
     *
     * null означает «показать нечего»: у задания без автопроверки ответа в базе
     * плагина нет, и это нормально.
     *
     * @param string $snapshot снимок позиции работы, JSON
     */
    public function workAnswerSummary(string $snapshot): ?string;

    /**
     * Создание нового задания по запросу редактора работы.
     *
     * Ядро не знает, чем является задание плагина, поэтому создать его может
     * только сам плагин. Ядро передаёт вид задания и контекст (автор, название)
     * и получает номер созданного задания, чтобы положить на него позицию.
     *
     * @param array<string,mixed> $context
     * @return int номер созданного задания
     */
    public function createTask(string $kind, array $context = []): int;

    /**
     * Понимает ли плагин такой вид задания — включая устаревшие.
     *
     * Нужно отдельно от taskKinds(): список видов отвечает на вопрос «что
     * учитель может создать сейчас», а этот — «что плагин ещё умеет показать».
     * Расходятся они у работ, созданных до смены правил: такие позиции
     * ссылаются на вид, которого в taskKinds() уже нет, и без этого метода
     * работа перестала бы открываться молча, без всякой ошибки.
     */
    public function knowsKind(string $kind): bool;

    /**
     * Адрес редактора задания для учителя.
     *
     * Своих маршрутов плагин объявляет сам, поэтому и адрес редактора строит
     * он же — по своему префиксу. null означает «этот вид заданий не редактируется
     * вручную»: работа не может требовать от автора вставки кода.
     */
    public function taskEditorUrl(TaskRef $task): ?string;

    /**
     * Сырые данные задания из базы плагина.
     *
     * Ядро знает только ссылку на задание и не знает, где оно лежит, поэтому
     * заполняет AttemptContext::taskData и EditorContext::taskData через этот
     * метод. Плагин возвращает свою строку целиком, ничего не разбирая: ядру
     * эти поля не нужны, они идут только обратно в редактор и проверку.
     *
     * @return array<string,mixed>
     */
    public function taskData(TaskRef $task): array;

    /**
     * Данные сразу нескольких заданий — одним обращением к базе.
     *
     * Ядро проходит по позициям работы, и на каждой вызывает taskData().
     * По одному обращению на позицию страница с двадцатью заданиями делала
     * двадцать одинаковых по форме запросов, хотя все они читают одни и те же
     * строки. Этот метод позволяет ядру собрать недостающее заранее.
     *
     * Реализация обязана вернуть столько же элементов, сколько пришло
     * ссылок, в том же порядке: пустой массив означает «задания нет», и это
     * отличается от «плагин не ответил».
     *
     * @param list<TaskRef> $tasks
     * @return list<array<string,mixed>> данные на каждый элемент, по порядку
     */
    public function taskDataBatch(array $tasks): array;

    /** Может ли пользователь редактировать принадлежащее плагину задание. */
    public function canManageTask(TaskRef $task, int $userId): bool;

    /**
     * Почему задание нельзя выпускать ученикам — или null, что можно.
     *
     * Проверка живёт у плагина, потому что только он знает, что значит
     * «заполнено» для его задания: у задания с вопросами это непустой текст и
     * хотя бы два заполненных варианта ответа, у вариативной задачи — условие
     * и формула, которая считается на краях диапазонов.
     *
     * Ядро спрашивает об этом при публикации работы. Раньше ту же проверку
     * выполняла публикация отдельного задания, но отдельной публикации больше
     * нет, и без переноса проверки на уровень работы ученик получил бы пустое
     * задание без единого варианта ответа.
     *
     * Текст возвращается как есть и показывается автору работы: «нельзя» без
     * объяснения заставляет автора гадать, какое именно задание не готово.
     */
    public function publicationBlocker(TaskRef $task): ?string;

/**
     * Фрагмент текста задания для списка работы — или пустая строка.
     *
     * Раньше здесь был обязательный «заголовок задания», и плагин обязан был
     * хранить его и верстать первым полем редактора. Заголовка больше нет: у
     * задания нет имени, которым его называют заранее, — есть условие, и в
     * списке работы показывается его начало.
     *
     * Требования к возвращаемому значению:
     *
     * - короткое: это подпись в списке, а не условие целиком, поэтому плагин
     *   решает сам, сколько знаков оставить;
     * - без разметки: значение попадает в текст узла списка и экранируется при
     *   выводе, но HTML-разметка там не нужна и только мешала бы;
     * - пустая строка — честный ответ, когда текста нет: список покажет
     *   только название типа задания, и это правда, а не недосмотр.
     *
     * Взывается часто и должно быть быстрым: это одна выборка из базы.
     */
    public function taskPreview(TaskRef $task): string;

    /**
     * Удаление задания.
     *
     * Ссылок из ядра на задания плагина по внешним ключам нет, поэтому
     * удалять их обязан владелец данных — он же чистит то, что завёл.
     *
     * Вызывается ядром после того, как позиция исчезла. Вернуть false
     * обязано и тогда, когда задание ещё используется в другой работе:
     * работы строятся из уникального набора заданий, но полагаться на это
     * в коде удаления нельзя — при спорах одного задания чужая работа
     * осталась бы с заданием, которого больше нет, и снятая работа снесла
     * бы чужое.
     *
     * @return bool true — задание удалено, false — осталось в других работах
     */
    public function deleteTask(TaskRef $task): bool;

    /**
     * Позиция работы удалена, прохождение по ней больше не нужно.
     *
     * Отдельный вызов, а не часть deleteTask(), потому что задание может
     * остаться в другой работе: тогда удалять его нельзя, а вот прохождения
     * по снятой позиции всё равно не должны оставаться в базе плагина.
     *
     * Порядок вызовов ядра: позиция удалена → deleteItem() → и только потом,
     * если задание осиротело, deleteTask().
     */
    public function deleteItem(TaskRef $task, int $itemId): void;
}
