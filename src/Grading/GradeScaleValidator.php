<?php

declare(strict_types=1);

namespace MyEdu\Grading;

/**
 * Проверка шкалы оценивания перед сохранением.
 *
 * Шкала обязана покрывать весь диапазон без пересечений и без дыр. Проверка
 * живёт здесь, а не в контроллере, потому что правило одно и то же для двух
 * форм: для процентов в редакторе работы и для баллов, если завтра появится
 * третий способ оценивания.
 *
 * Что считается дырой и пересечением:
 *
 * * дыра — промежуток между диапазонами, куда не попадает ни одна оценка.
 *   Ученик с таким результатом получил бы оценку по умолчанию, и выглядело бы
 *   это так, будто учитель назначил её сам;
 * * пересечение — два диапазона, накрывающих одно и то же число. Оценка
 *   выбиралась бы первой по списку, и вторая строка молчала бы;
 * * пустой диапазон — «от 10 до 9». Оценка недостижима вовсе.
 *
 * Диапазоны обязаны примыкать: верхняя граница предыдущего плюс один шаг
 * равна нижней границе следующего. Требование строгое, и это не придирчивость:
 * при баллах с шагом в половину балла промежуток в 0.5 — это ровно то
 * значение, которое не попадёт ни в один диапазон, и на разборах оно выглядело
 * бы как ошибка подсчёта.
 */
final class GradeScaleValidator
{
    /** Оценки фиксированы: в школьной России их четыре, и выбирать их автору незачем. */
    public const GRADES = [5, 4, 3, 2];

    /** Шаг процентов: целый. */
    public const PERCENT_STEP = 1.0;

    /** Шаг баллов: половина балла на границе диапазона — обычное дело. */
    public const SCORE_STEP = 0.5;

    /**
     * Цвета оценки: не названия, а ключи токенов темы.
     *
     * Именно ключи, а не готовые шестнадцатеричные коды: цвета в проекте
     * берутся из токенов, иначе в тёмной теме подпись на белом фоне
     * превратилась бы в нечитаемое пятно. Свой цвет у каждой оценки — это
     * `var(--success)`, `var(--primary)` и так далее.
     */
    public const COLORS = ['success', 'primary', 'warning', 'danger'];

    /**
     * Те же четыре цвета в виде HEX — для поля выбора цвета в браузере.
     *
     * Нативное поле `<input type="color">` понимает только `#rrggbb`, и без
     * перевода форма не смогла бы показать текущий цвет строки. Значения
     * обязаны совпадать с `--grade-*` из `public/assets/css/theme.css`:
     * образец в форме и краска на экране берутся из двух мест и должны быть
     * одним и тем же цветом.
     */
    public const COLOR_HEX = [
        'success' => '#2fb344',
        'primary' => '#066fd1',
        'warning' => '#f59f00',
        'danger'  => '#d63939',
    ];

    /**
     * Цвет каждой оценки по умолчанию.
     *
     * Зелёный, синий, оранжевый, красный — привычная раскраска журнала,
     * и по ней шкалу читают без чтения чисел: пятёрка зелёная, двойка
     * красная. У прежних шкал цвета не было вовсе, и подставлять этот
     * набор — значит показать учителю то, что он и так ожидал увидеть.
     */
    public const DEFAULT_COLORS = [
        5 => 'success',
        4 => 'primary',
        3 => 'warning',
        2 => 'danger',
    ];

    /**
     * Цвет оценки из значения формы или из прежних данных.
     *
     * Значение приходит из браузера, поэтому сверяется: в `criteria` должны
     * попасть либо одно из четырёх известных названий, либо собственный цвет
     * в виде `#rrggbb` — и больше ничего. Всё прочее отбрасывается и
     * заменяется цветом оценки по умолчанию: произвольный текст сюда не
     * годится, а он потом попадает в разметку результата ученика.
     *
     * Свой цвет — решение владельца от 24.10.2026 (задача 4): автор может
     * взять в палитре браузера любую краску, и она сохраняется в базу.
     * Короткая форма `#abc` тоже принимается: браузер отдаёт её, скопировав
     * значение из других мест.
     *
     * Пусто и незнакомое — это цвет по умолчанию для оценки, а не отказ.
     * Так ведут себя прежние шкалы, сохранённые до появления цвета: они не
     * должны требовать пересохранения и не должны остаться бесцветными.
     */
    public static function normalizeColor(mixed $value, int $grade): string
    {
        $value = is_scalar($value) ? strtolower(trim((string) $value)) : '';

        if (in_array($value, self::COLORS, true)) {
            return $value;
        }

        if (preg_match('/^#([0-9a-f]{3}|[0-9a-f]{6})$/', $value) === 1) {
            return $value;
        }

        return self::DEFAULT_COLORS[$grade] ?? 'primary';
    }

    /**
     * Цвет в виде HEX — для значения нативного поля выбора цвета.
     *
     * Название из палитры переводится по `COLOR_HEX`, свой цвет проходит как
     * есть: поле `<input type="color">` понимает только `#rrggbb` и молча
     * показало бы чёрный образец на месте названия.
     */
    public static function colorHex(string $color): string
    {
        if (preg_match('/^#([0-9a-f]{3}|[0-9a-f]{6})$/', $color) === 1) {
            return $color;
        }

        return self::COLOR_HEX[$color] ?? self::COLOR_HEX['primary'];
    }

    /**
     * Цвет — название из палитры или свой.
     *
     * Для разметки: названия дают готовые CSS-классы, а свой цвет не имеет
     * класса и передаётся атрибутом `data-grade-color` — см.
     * `public/assets/js/grade-color.js`.
     */
    public static function isPaletteColor(string $color): bool
    {
        return in_array($color, self::COLORS, true);
    }

    /**
     * Шкала по умолчанию в процентах.
     *
     * Те же значения, что раньше стояли в подсказке под полями: учитель,
     * который ничего не трогал, должен получить ту же шкалу, что и раньше.
     *
     * @return list<array{grade:int,from:float}>
     */
    public static function percentDefaults(): array
    {
        return [
            ['grade' => 5, 'from' => 85.0],
            ['grade' => 4, 'from' => 70.0],
            ['grade' => 3, 'from' => 50.0],
            ['grade' => 2, 'from' => 0.0],
        ];
    }

    /**
     * Шкала по умолчанию в баллах: сумма делится на четыре равные части.
     *
     * Деление поровну, а не «по пятой части от максимума», потому что иначе
     * верхний диапазон оказывался бы уже остальных и самый высокий процент
     * работы не давал бы пятёрки.
     *
     * @return list<array{grade:int,from:float,to:float}>
     */
    public static function scoreDefaults(float $total): array
    {
        $total = round(max(0.0, $total), 2);

        /*
         * Работа без единой цены в балловом режиме не оценивается вовсе: у
         * неё нет верхней границы, и четыре диапазона выродились бы в четыре
         * нуля. Такая шкала честнее нулевой, но и она не должна быть «неверной»
         * при проверке — отсюда ровно нули, а не отрицательные половины.
         */
        if ($total <= 0.0) {
            $rows = [];

            foreach (self::GRADES as $grade) {
                $rows[] = ['grade' => $grade, 'from' => 0.0, 'to' => 0.0];
            }

            return $rows;
        }

        $part = round($total / 4.0, 2);

        /*
         * Шаг границ берётся из суммы цен, а не задаётся половиной балла.
         *
         * Раньше деление шло ровно на четыре части и давало четверти: при сумме
         * 17 это 12.75, 8.5 и 4.25. Сами по себе числа верные, но поле в форме
         * объявлено с шагом 0.5, и браузер отвергал их все — вместе с верхними
         * границами ровно четыре поля на любой работе, чья сумма не делится на
         * два. Человек нажимал «Сохранить» на полностью заполненной форме и
         * получал «проверьте 4 пол.», а отмечать было нечего: значения стояли
         * те, которые сервер сам подставил.
         *
         * Теперь границы по умолчанию ложатся на тот же шаг, который умеет
         * поле, и форма принимает собственные значения. Мелкие суммы, где
         * половина балла шире диапазона, получают шаг мельче.
         */
        $grid = self::scoreGrid($total);
        $part = round(round($total / 4.0 / $grid) * $grid, 2);

        /*
         * Шаг, на который диапазоны отступают друг от друга.
         *
         * Зазор обязан быть кратен шагу границ. Иначе между «до пятёрки» и «от
         * четвёрки» остаётся полоска, куда попадают числа, которые набрать можно:
         * при сумме 2.1 и шаге 0.1 зазор в 0.25 оставлял бы 1.4 и 1.5 без оценки.
         *
         * Зазор исчезает, когда он не помещается в диапазон: при сумме двух
         * баллов и меньше половина балла шире самого диапазона, и диапазоны
         * смыкаются впритык — набрать такое число нельзя, и выбирается высшая из
         * двух оценок, на границе которых оно попало.
         */
        $join = ($total <= 4.0 * $grid || $part < 2.0 * $grid) ? 0.0 : $grid;

        $rows = [];
        $from = round($total - $part, 2);

        foreach (self::GRADES as $index => $grade) {
            /*
             * Верхняя граница — нижняя граница следующей, более высокой оценки
             * минус шаг: 20 «до» пятёрки и 19.5 «от» четвёрки смыкаются без
             * зазора, потому что 19.75 набрать нельзя.
             *
             * Границы считаются накоплением сверху вниз, а не умножением шага на
             * индекс: при сумме 7.5 умножение давало 1.875 трижды и на последнем
             * шаге — минус ноль из-за накопленной погрешности.
             *
             * Зажим снизу в ноль обязателен: при сумме в три балла шаг в половину
             * балла не помещается в последний диапазон, и вычитание уводило
             * границу в минус. Отрицательная верхняя граница — это и неверное
             * число в поле, и отказ сервера при сохранении.
             */
            $to = $index === 0
                ? $total
                : max(0.0, round($rows[$index - 1]['from'] - $join, 2));

            $rows[] = ['grade' => $grade, 'from' => $from, 'to' => $to];

            $from = max(0.0, round($from - $part, 2));
        }

        /*
         * Диапазон самой низкой оценки начинается с нуля — по определению, это
         * всё, что набрано ниже порога тройки.
         *
         * Накопление округляет шаг вверх, и на суммах, не делящихся на четыре
         * шага, остаток не съедался: у работы на 2.1 балла нижняя граница
         * получалась 0.1, и балл 0.1 не попадал ни в один диапазон — работа не
         * засчитывалась целиком.
         */
        $rows[count($rows) - 1]['from'] = 0.0;

        return $rows;
    }

    /**
     * Шаг, кратный которому поле границы в баллах умеет принимать значение.
     *
     * Половина балла — обычный случай, но при сумме в один-два балла четверть
     * диапазона в неё не помещается, и шаг мельче. Шаг обязан быть тем же самым,
     * по которому считаются границы по умолчанию: иначе форма отвергнет то,
     * что сервер в неё и положил.
     */
    public static function scoreGrid(float $total): float
    {
        $total = round($total, 2);

        foreach ([self::SCORE_STEP, 0.25, 0.1, 0.05, 0.01] as $candidate) {
            /*
             * Шаг обязан делить сумму. Верхняя граница самой высокой оценки равна
             * сумме цен, и на некратном шаге она сама оказалась бы вне поля:
             * форма отвергла бы значение, которое сервер в неё и положил.
             */
            if ($total / 4.0 >= $candidate
                && abs($total / $candidate - round($total / $candidate)) < 0.0001) {
                return $candidate;
            }
        }

        return 0.01;
    }

    /**
     * Шаг смыкания диапазонов, посчитанный по самим данным.
     *
     * Половина балла — обычный случай, но при сумме в один-два балла четыре
     * диапазона не помещаются в неё, и зазор в 0.5 недосяжим. Тогда шагом
     * считается наименьшая разница между соседними «от»: он и есть минимальный
     * шаг этой шкалы, и дыра в него не может поместиться по построению.
     *
     * @param array<int,array{from:float|null,to:float|null}> $byGrade
     */
    private static function joinStep(array $byGrade): float
    {
        $steps = [];
        $previous = null;

        foreach (self::GRADES as $grade) {
            if (!isset($byGrade[$grade]) || $byGrade[$grade]['from'] === null) {
                continue;
            }

            $from = (float) $byGrade[$grade]['from'];

            if ($previous !== null && $from < $previous) {
                $steps[] = $previous - $from;
            }

            $previous = $from;
        }

        if ($steps === []) {
            return self::SCORE_STEP;
        }

        return max(0.0, min(self::SCORE_STEP, min($steps)));
    }

    /**
     * Проверка диапазонов.
     *
     * @param list<array{grade:int,from:float|null,to:float|null}> $rows
     *
     * @return array{
     *     ok:bool,
     *     messages:list<string>,
     *     badFrom:list<int> оценки с неверной нижней границей,
     *     badTo:list<int> оценки с неверной верхней границей
     * }
     */
    public static function check(array $rows, bool $byScore, float $percentMax = 100.0): array
    {
        $step = $byScore ? 0.0 : self::PERCENT_STEP;
        $messages = [];
        $badFrom = [];
        $badTo = [];

        $byGrade = [];

        foreach ($rows as $row) {
            $grade = (int) ($row['grade'] ?? 0);
            $from = $row['from'] ?? null;
            $to = $row['to'] ?? null;

            if (!in_array($grade, self::GRADES, true)) {
                $messages[] = 'Оценка ' . $grade . ' не входит в набор 2, 3, 4, 5';

                continue;
            }

            if ($from === null || !is_finite($from)) {
                $messages[] = 'Не заполнена нижняя граница для оценки ' . $grade;
                $badFrom[] = $grade;

                continue;
            }

            if ($from < 0.0) {
                $messages[] = 'Нижняя граница оценки ' . $grade . ' отрицательна';
                $badFrom[] = $grade;
            }

            if (!$byScore && $from > $percentMax) {
                $messages[] = 'Нижняя граница оценки ' . $grade . ' больше ' . self::num($percentMax) . '%';
                $badFrom[] = $grade;
            }

            if ($byScore) {
                if ($to === null || !is_finite($to)) {
                    $messages[] = 'Не заполнена верхняя граница для оценки ' . $grade;
                    $badTo[] = $grade;
                } elseif ($to < $from) {
                    $messages[] = 'У оценки ' . $grade . ' «до» меньше, чем «от»';
                    $badFrom[] = $grade;
                    $badTo[] = $grade;
                }
            }

            $byGrade[$grade] = ['from' => $from, 'to' => $to];
        }

        /*
         * Порядок проверяется по убыванию оценки: 5 начинается там, где 4
         * кончается.
         *
         * В процентах верхней границы нет — она вычисляется из следующей
         * строки, — и дыры быть не может: диапазон «от 50%» тянется от
         * границы четвёрки до 50% и всегда заполнен. Поэтому проверяется
         * только строгое убывание: равные границы оставили бы оценку с пустым
         * диапазоном, а «наоборот» — пересечение, в котором выбор зависил бы от
         * того, как отсортировали строки в базе.
         *
         * В баллах верхняя граница задана явно, и там нужны обе проверки:
         * примыкание к следующей, более высокой оценке (иначе дыра) и
         * непересечение с ней же.
         */
        $step = $byScore ? self::joinStep($byGrade) : self::PERCENT_STEP;

        $previousFrom = null;
        $previousGrade = null;

        foreach (self::GRADES as $grade) {
            if (!isset($byGrade[$grade])) {
                continue;
            }

            ['from' => $from, 'to' => $to] = $byGrade[$grade];

            if ($previousGrade !== null) {
                if (!$byScore) {
                    if ($from >= (float) $previousFrom) {
                        $messages[] = 'Нижняя граница оценки ' . $grade
                            . ' должна быть ниже границы оценки ' . $previousGrade
                            . ' — иначе диапазон ' . $grade . ' пустой';
                        $badFrom[] = $grade;
                    }
                } else {
                    /*
                     * Граница между диапазонами — это «до» текущей оценки и
                     * «от» предыдущей, более высокой. Расстояние между ними
                     * не может быть отрицательным (тогда диапазоны
                     * пересекаются) и не может быть больше шага (тогда между
                     * ними наберут баллов, которые не попадут ни в один
                     * диапазон). Ноль — касание: число попадёт в оба
                     * диапазона, но выбор однозначен, потому что оценки
                     * перебираются от высшей к низшей.
                     */
                    $boundary = (float) $previousFrom - (float) $to;

                    if ($boundary < 0.0) {
                        $messages[] = 'Диапазоны оценок ' . $previousGrade . ' и ' . $grade
                            . ' пересекаются: «до» для оценки ' . $grade
                            . ' должно быть меньше, чем «от» для оценки ' . $previousGrade;
                        $badTo[] = $grade;
                    } elseif ($boundary > $step + 0.0001) {
                        $messages[] = 'Между диапазонами оценок ' . $previousGrade . ' и ' . $grade
                            . ' дыра в ' . self::num(round($boundary - $step, 2))
                            . ' — она не попадёт ни в одну оценку';
                        $badTo[] = $grade;
                    }
                }
            }

            // Нижняя граница самой слабой оценки обязана быть нулём, иначе
            // результат ниже неё не попадёт ни в какой диапазон.
            if ($grade === 2 && abs($from) > 0.0001) {
                $messages[] = 'Нижняя граница оценки 2 должна быть 0: всё, что ниже неё, '
                    . 'не попало бы ни в один диапазон';
                $badFrom[] = 2;
            }

            $previousGrade = $grade;
            $previousFrom = $from;
        }

        if ($byScore) {
            /*
             * Верхняя граница пятёрки должна доставать до суммы цен заданий:
             * работа, выполненная полностью, обязана давать пятёрку. Меньший
             * максимум означал бы, что часть работы не достаёт ни до какой
             * оценки, и это заметно только по разборам.
             */
            $best = $byGrade[5] ?? null;

            if ($best !== null && $best['to'] !== null && $percentMax > 0.0
                && abs($best['to'] - $percentMax) > 0.0001) {
                $messages[] = 'Верхняя граница оценки 5 должна быть равна сумме цен: '
                    . self::num($percentMax) . ', сейчас ' . self::num($best['to']);
                $badTo[] = 5;
            }
        }

        return [
            'ok'       => $messages === [],
            'messages' => $messages,
            'badFrom'  => array_values(array_unique($badFrom)),
            'badTo'    => array_values(array_unique($badTo)),
        ];
    }

    /** Число без хвостовых нулей: 15,5 и не 15,50. */
    public static function num(float $value): string
    {
        return rtrim(rtrim(number_format($value, 2, ',', ' '), '0'), ',');
    }

    /** То же для шаблонов: без хвостовых нулей, но без пробела между разрядами. */
    public static function formatNumber(float $value): string
    {
        return rtrim(rtrim(number_format($value, 2, ',', ''), '0'), ',');
    }
}