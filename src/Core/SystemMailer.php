<?php

declare(strict_types=1);

namespace MyEdu\Core;

/**
 * Диагностическое письмо: доходят ли письма до получателя вообще.
 *
 * Отдельное письмо, а не письмо подтверждения. Подтверждение, отправленное
 * администратору, привело бы его на страницу «ссылка недействительна» — а
 * проверять нужно именно доставку, и никакой связи с подтверждением у
 * письма быть не должно.
 *
 * Путь отправки при этом самый обычный: тот же драйвер и те же заголовки, что
 * у письма подтверждения. Если тестовое письмо не приходит, не доходят и
 * письма новым пользователям.
 */
final class SystemMailer
{
    public function __construct(private readonly MailerInterface $mailer)
    {
    }

    public function sendTest(string $to, string $fullName): bool
    {
        $subject = 'Тестовое письмо из системы контроля знаний';

        $name = trim($fullName) === '' ? '' : trim($fullName) . ', ';

        $text = "Здравствуйте, {$name}!\n\n"
            . "Это тестовое письмо. Оно проверяет, доходят ли письма системы\n"
            . "до получателя, и ни к чему не обязывает.\n\n"
            . "Если письмо читается — отправка настроена верно.\n"
            . "Если письмо не пришло, откройте в панели «Настройки сайта»:\n"
            . "там показаны драйвер отправки, адрес отправителя и причина\n"
            . "последнего отказа.\n";

        return $this->mailer->send(new MailMessage($to, $subject, $text));
    }
}
