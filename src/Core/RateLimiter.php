<?php

declare(strict_types=1);

namespace MyEdu\Core;

/**
 * Ограничение частоты запросов на чувствительные адреса.
 *
 * Что закрывает: бесконечный поток однотипных запросов с одного адреса —
 * перебор пароля, массовая регистрация, спам письмами для сброса пароля, тысячи
 * загрузок файлов. Вход уже закрыт `LoginThrottle`; здесь защищены остальные
 * адреса, где один и тот же запрос можно повторять без пользы.
 *
 * Почему не все POST подряд. Учитель за минуту может честно сделать сотню
 * запросов: перетаскивать карточки, переставлять строки, сохранять задания.
 * Общий счётчик выставил бы его за работу, а человек решил бы, что система
 * сбоит. Поэтому адреса задаются списком, а пределы у каждого свои: для входа и
 * сброса пароля — десятки, для загрузки картинки — единицы в минуту.
 *
 * Счёт скользящий по окну, а не «сброс по расписанию»: окно считается от первого
 * запроса, поэтому лавина не пройдёт и на стыке двух минут.
 *
 * Таблица короткоживущая: запись удаляется сама по истечении окна, поэтому
 * чистить её вручную не нужно. Подметание при записи — на случай, если адрес
 * замолчал: без него строки копились бы вечно.
 */
final class RateLimiter
{
    public function __construct(
        private readonly Database $db,
        private readonly int $windowSeconds = 60
    ) {
    }

    /**
     * Проверить и записать запрос.
     *
     * @param string $bucket имя группы адресов: счётчики раздельные, и перебор
     *                       пароля не отнимает лимит у загрузки картинки
     * @param int    $limit  сколько запросов этой группы допустимо за окно
     * @param string $who    кто именно: идентификатор человека или адрес
     *
     * @return int 0 — можно, сколько секунд ждать — нельзя
     */
    public function hit(string $bucket, int $limit, string $who): int
    {
        if ($limit <= 0) {
            return 0;
        }

        /*
         * Счётчик не обязан быть: обновлён код, а миграция ещё не применена —
         * и вместо работающего сайта каждый запрос к ограниченному адресу
         * падал бы с «таблицы нет». Отсутствие ограничения куда безопаснее
         * отказа: сайт продолжает работать, а что ограничение не настроено,
         * покажет проверка миграций.
         *
         * Причина пишется в журнал: молча проглоченная ошибка выглядит как
         * «ограничение работает, просто не срабатывает», и искать её потом
         * приходится по догадкам.
         */
        try {
            return $this->count($bucket, $limit, $who);
        } catch (\Throwable $e) {
            error_log('[rate] счётчик недоступен, запрос пропущен: ' . $e->getMessage());

            return 0;
        }
    }

    /**
     * @return int 0 — можно, сколько секунд ждать — нельзя
     */
    private function count(string $bucket, int $limit, string $who): int
    {
        $key = $this->key($bucket, $who);
        $now = time();

        $row = $this->db->one(
            'SELECT window_started_at, hits FROM rate_limits WHERE limit_key = :k',
            ['k' => $key]
        );

        if ($row === null) {
            $this->db->run(
                'INSERT INTO rate_limits (limit_key, window_started_at, hits) VALUES (:k, :at, 1)',
                ['k' => $key, 'at' => $this->stamp($now)]
            );

            return 0;
        }

        $started = strtotime((string) $row['window_started_at']) ?: $now;
        $hits = (int) $row['hits'];

        /*
         * Окно истекло — счёт начинается заново, но строка та же: так не
         * плодится запись на каждый запрос.
         */
        if ($now - $started >= $this->windowSeconds) {
            $this->db->run(
                'UPDATE rate_limits SET window_started_at = :at, hits = 1 WHERE limit_key = :k',
                ['k' => $key, 'at' => $this->stamp($now)]
            );

            return 0;
        }

        if ($hits >= $limit) {
            return max(1, $this->windowSeconds - ($now - $started));
        }

        $this->db->run(
            'UPDATE rate_limits SET hits = hits + 1 WHERE limit_key = :k',
            ['k' => $key]
        );

        /*
         * Подметание: записи, чьё окно давно прошло, больше не понадобятся.
         * Идёт не каждый раз, а на каждый сотый запрос — иначе лишний DELETE
         * платил бы за себя на каждом обращении.
         */
        if ($hits % 100 === 0) {
            $this->db->run(
                'DELETE FROM rate_limits WHERE window_started_at < :deadline',
                ['deadline' => $this->stamp($now - ($this->windowSeconds * 10))]
            );
        }

        return 0;
    }

    /*
 * Время в базу и время из базы обязаны читаться в одной шкале.
 *
 * Запись делается через date(), чтение — через strtotime(), и обе функции
 * смотрят на локальную зону PHP, которую приложение выставляет в начале
 * запроса. Смешивать их нельзя: запись в UTC при чтении по местной зоне
 * сдвигает окно на разницу часов, окно выходит истёкшим немедленно, и счётчик
 * обнуляется на каждом запросе — ограничение не срабатывает никогда, при этом
 * ничего не падает и выглядит исправным. Так и вышло при первой проверке:
 * счётчик рос, но порог не достигался никогда.
 *
 * Ровно так же поступает LoginThrottle, и это не совпадение: два счётчика в
 * одной базе обязаны считать в одной шкале времени.
 */
    private function stamp(int $when): string
    {
        return date('Y-m-d H:i:s', $when);
    }

    /**
     * Ключ записи — хеш, а не то, из чего он составлен.
     *
     * В ключе лежит адрес и, возможно, идентификатор человека, а таблица
     * показывает всё, что в неё положили. Хеш убирает и лишние байты в имени
     * индекса, и возможность узнать по таблице, кто ходил чаще других.
     */
    private function key(string $bucket, string $who): string
    {
        return hash('sha256', $bucket . '|' . $who);
    }
}