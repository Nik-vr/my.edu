<?php

declare(strict_types=1);

namespace MyEdu\Core;

/**
 * Отправка писем.
 *
 * Драйвер выбирается в config.php — в config.php driver'log'. Он пишет письма
 * в var/log/mail.log вместо отправки: это позволяет проверять ссылки
 * подтверждения в тестах и при разработке без почтового сервера.
 *
 * В production используется драйвер 'mail' (функция mail(), есть на любом
 * шаред-хостинге) либо 'smtp' (собственный клиент на fsockopen, если mail()
 * на сервере не работает или письма уходят в спам).
 */
interface MailerInterface
{
    public function send(MailMessage $message): bool;

    /** Человекочитаемое имя драйвера для интерфейса. */
    public function name(): string;

    /**
     * Причина последнего отказа, null — если последняя отправка прошла.
     *
     * Нужна странице настроек: драйвер пишет причину и в журнал PHP, но на
     * шаред-хостинге журнал читать неудобно, а человеку нужно понять, почему
     * письма не уходят, прямо на странице.
     */
    public function lastError(): ?string;

    /**
     * Предупреждение последней отправки при УСПЕШНОЙ отправке.
     *
     * Диагностика проблемы владельца (24.10.2026, задача 7): письмо «принято
     * к отправке», а до адресата не доходит. При этом PHP может сообщать о
     * проблеме прямо при успехе — например, «не удалось выполнить
     * /usr/sbin/sendmail», и раньше это предупреждение подавлялось символом
     * @ и исчезало: человек видел честный успех, а письма нет ни в почте, ни
     * в логах.
     *
     * null — предупреждений не было. Отличается от lastError(): тот называет
     * отказ (письмо не принято), этот — сомнение (принято, но с проблемой).
     */
    public function lastWarning(): ?string;
}