<?php

declare(strict_types=1);

namespace MyEdu\Core;

/**
 * Начало текста задания для подписи в списке работы.
 *
 * Задания хранят условие как наборный HTML из визуального редактора: теги,
 * переносы, неразрывные пробелы. В списке работы от задания нужна одна строка,
 * и показывать там разметку нельзя — она попадёт в текст узла и либо вылезет
 * метками, либо будет вырезана наполовину.
 *
 * Правила простые, потому что задача обратная: не разобрать, а показать начало
 * и не соврать.
 *
 * - Разметка снимается целиком, а не «по кускам»: обрыв тега посередине
 *   оставляет в строке обрывок вроде `</p` , который виден читателю.
 * - Пробелы приводятся к одному: в наборном тексте их десятки подряд, и без
 *   этого строка переносится по случайному месту.
 * - Обрыв ставится на границе слова, а не посередине: «Сколько будет 12 м» —
 *   обрывок, который читается как ошибка.
 * - Пустой результат — честный ответ «текста нет», а не замена на «Задание»:
 *   выдуманное имя выглядело бы как настоящее.
 */
final class TextFragment
{
    /** Сколько знаков показывать. Многострочный текст в карточке не нужен. */
    public const LIMIT = 120;

    /**
     * Короткая однострочная выдержка из текста с разметкой.
     *
     * @param string|null $html   условие задания как есть, вместе с разметкой
     * @param int         $limit сколько знаков оставить; 0 — без обрыва
     */
    public static function from(?string $html, int $limit = self::LIMIT): string
    {
        if ($html === null) {
            return '';
        }

        /*
         * Разрыв тега перед склейкой: иначе `</p><p>` склеится в `</p><p>` без
         * разделителя и слова по краям схлопнутся в одно. На деле регулярка
         * `strip_tags` делает это сама, но полагаться на частность поведения
         * strip_tags по версиям PHP здесь незачем.
         */
        $text = (string) preg_replace('/<[^>]*>/', ' ', $html);
        $text = html_entity_decode($text, ENT_QUOTES | ENT_HTML5, 'UTF-8');
        $text = (string) preg_replace('/\s+/u', ' ', $text);
        $text = trim($text);

        if ($text === '' || $limit <= 0 || mb_strlen($text, 'UTF-8') <= $limit) {
            return $text;
        }

        $cut = mb_substr($text, 0, $limit, 'UTF-8');

        // Обрыв по границе слова: последнее пробел перед срезом.
        $space = mb_strrpos($cut, ' ', 0, 'UTF-8');

        if ($space !== false && $space > 0) {
            $cut = mb_substr($cut, 0, $space, 'UTF-8');
        }

        return rtrim($cut, " \t\n\r\0\x0B,.;:!?-") . '…';
    }
}