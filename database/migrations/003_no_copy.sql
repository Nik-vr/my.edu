-- Запрет копирования текста задания.
--
-- Что это: работа может быть выдана с запретом копирования — на странице
-- прохождения подключается скрипт, который не даёт выделить и скопировать
-- текст вопроса. Нужен там, где материалы авторские и их раздача не
-- предполагается: тренировочная работа, пробник, внутренняя проверка.
--
-- Почему отдельная миграция, а не правка снимка схемы: снимок — это состояние
-- новой установки, а у уже стоящих баз колонки нет. Миграция повторяема и
-- ничего не переписывает: у работы без запрета новое поле равно нулю, то есть
-- поведение остаётся прежним.
--
-- Значение по умолчанию — 0: запрет выключен, пока о нём не попросили.
-- Иначе у учителя, который привык к обычному прохождению, вдруг перестал бы
-- работать обычный копипаст ответа, и он искал бы причину.

SET @column_exists := (
    SELECT COUNT(*)
    FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'assignments'
      AND COLUMN_NAME = 'no_copy'
);

SET @sql := IF(
    @column_exists > 0,
    'SELECT 1',
    'ALTER TABLE `assignments` ADD COLUMN `no_copy` TINYINT(1) NOT NULL DEFAULT 0 COMMENT ''запретить копирование текста задания при выполнении'''
);

PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
