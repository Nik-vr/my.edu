-- Личная тема оформления: тёмная или светлая.
--
-- Что это: человек выбирает тему один раз — в профиле или кнопкой в шапке —
-- и видит систему в этом виде на всех страницах и после каждого входа.
-- Выбор хранится отдельно у сотрудника и отдельно у ученика, как и размер
-- шрифта: у них разные таблицы и разные страницы профиля, но свойства одно —
-- «так мне удобно смотреть», и оно не смешивается с чужим.
--
-- Почему сервер, а не localStorage (решение владельца от 24.10.2026, волна E):
-- прежний выбор жил в браузере, и на другом устройстве или после очистки
-- хранилища человек получал тёмную тему, хотя выбирал светлую. Тема теперь
-- живёт в профиле: сервер ставит её в разметку до первой отрисовки, поэтому
-- страница не мигает, и выбор не зависит от состояния браузера.
--
-- Зачем отдельная миграция, а не только снимок схемы: снимок описывает
-- новую установку, а на уже стоящих базах колонки нет, и у человека без неё
-- просто нечего читать. Миграция повторяема: проверка идёт через
-- information_schema, а не через `ADD COLUMN IF NOT EXISTS` — такой синтаксис
-- понимает только MariaDB.
--
-- Тип — VARCHAR со значениями dark/light, а не TINYINT с числом:
--   1. Значение читается как есть в разметке (`data-theme="light"`), и
--      переводить число в слово пришлось бы в двух местах — в оболочке и в
--      форме профиля, где они легко разошлись бы.
--   2. В базе, которую человек смотрит руками, написано слово, а не «1»,
--      и гадать, какое это число, не нужно.
--   3. Пустые значения и слова не из списка — тоже тёмная тема, поэтому
--      ограничение ENUM здесь не даёт ничего, а при расширении списка
--      пришлось бы менять ENUM.
--
-- Значение по умолчанию — dark: пока человек ничего не выбрал, он видит
-- систему как задумано, а светлая тема остаётся его сознательным выбором.

SET @column_exists := (
    SELECT COUNT(*)
    FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'users'
      AND COLUMN_NAME = 'theme'
);

SET @sql := IF(
    @column_exists > 0,
    'SELECT 1',
    'ALTER TABLE `users` ADD COLUMN `theme` VARCHAR(8) NOT NULL DEFAULT ''dark'' COMMENT ''личная тема: dark, light'''
);

PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

SET @column_exists := (
    SELECT COUNT(*)
    FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'students'
      AND COLUMN_NAME = 'theme'
);

SET @sql := IF(
    @column_exists > 0,
    'SELECT 1',
    'ALTER TABLE `students` ADD COLUMN `theme` VARCHAR(8) NOT NULL DEFAULT ''dark'' COMMENT ''личная тема: dark, light'''
);

PREPARE stmt FROM @sql;
EXECUTE stmt;
