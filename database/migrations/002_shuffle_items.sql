-- Перемешивание заданий работы.
--
-- Что это: работа выдаётся ученику не в том порядке, в котором задания
-- расставлены в редакторе, а в случайном. Порядок выбирается один на
-- попытку и закреплён за ней, поэтому ученик не видит, как задания
-- переставляются при переходе туда-обратно.
--
-- Почему отдельная миграция, а не правка снимка схемы: снимок — это состояние
-- новой установки, а у уже стоящих баз колонки нет. Миграция повторяема
-- (`IF NOT EXISTS` в MySQL такого не умеет, поэтому проверка идёт через
-- information_schema) и ничего не переписывает: у работа без перемешивания
-- новое поле равно нулю, то есть поведение остаётся прежним.
--
-- Значение по умолчанию — 0: перемешивание выключено, пока о нём не
-- попросили. Иначе у учителя, который привык к порядку, вдруг поехали бы
-- задания, и он искал бы причину.

SET @column_exists := (
    SELECT COUNT(*)
    FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'assignments'
      AND COLUMN_NAME = 'shuffle_items'
);

SET @sql := IF(
    @column_exists > 0,
    'SELECT 1',
    'ALTER TABLE `assignments` ADD COLUMN `shuffle_items` TINYINT(1) NOT NULL DEFAULT 0 COMMENT ''выдавать задания ученику в случайном порядке'''
);

PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
