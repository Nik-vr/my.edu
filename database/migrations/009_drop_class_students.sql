-- Добивка таблицы class_students на тех базах, где она осталась.
--
-- Зачем отдельная миграция, если миграция 007 уже убирает `class_students`.
--
-- 007 делает это одной строкой в общем потоке переделки: внутри неё таблица
-- читается, данные переносятся в колонку `students.class_id`, и только потом
-- таблица снимается. Если на конкретной базе 007 встала на середине (нет
-- прав, оборвалось соединение, шаред-хостинг с лимитом времени), таблица
-- осталась: часть работ уже по новой схеме, а старая связка висит рядом.
-- Повторно 007 не отработать — она в журнале может стоять применённой, а может
-- и падать по уже выполненным шагам. Поэтому добивка идёт отдельным файлом:
-- он содержит ровно одно удаление, повторяем, и не трогает ничего, кроме
-- лишней таблицы.
--
-- Повторяемость. `DROP TABLE IF EXISTS` сам по себе идемпотентен: отсутствие
-- таблицы — не ошибка. Проверка идёт без MariaDB-синтаксиса вроде
-- `DROP TABLE IF EXISTS` с условием — этот файл его и использует, он переносим.
-- Ничего, кроме удаления одной таблицы, здесь нет, и на целевой схеме
-- (`database/schema.sql`) таблицы уже нет — снимок её не содержит.
--
-- Что остаётся вручную: ничего. Файл применяется обычным порядком миграций,
-- при выкатке на шаред-хостинг поднимается сам, консоль не нужна.

DROP TABLE IF EXISTS `class_students`;
