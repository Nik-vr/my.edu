/* ==========================================================================
   Отметка «скрипты работают» до первой отрисовки.

   Подключается в шапке без defer: скрипт должен выполниться раньше, чем браузер
   нарисует страницу.

   Тема здесь больше не решается: выбор живёт в профиле человека (решение
   владельца от 24.10.2026, волна E), сервер ставит его в саму разметку —
   `<html data-theme="…">` — до того, как браузер увидит страницу. Раньше
   скрипт читал localStorage и переставлял атрибут, и выбор терялся на другом
   устройстве, при очистке хранилища и у человека, который просто вошёл с
   нового компьютера.

   Без скриптов страница остаётся в той теме, что пришла с сервера: атрибут
   уже стоит в разметке, и ничего переставлять не нужно.

   Отметка data-js ставится именно здесь: скрипт в шапке выполняется до разбора
   тела, и этого достаточно, чтобы окна не показывались как обычные блоки.

   Пока отметки нет, `html:not([data-js]) [data-modal]` показывает окно
   обычным блоком — так страница остаётся рабочей без JavaScript. Но окно
   лежит в разметке, и до `modal-open.js` оно успевает раздут документ:
   страница с формой задания становится почти на тысячу пикселей выше,
   браузер уводит прокрутку к раздутому блоку, а скрипт окно закрывает и
   документ сжимается. Прокрутка остаётся внизу, и закрытие окна выглядит
   так, будто страницу утащило в самый конец.

   Отметка ставится в шапке именно потому, что здесь скрипт ещё гарантированно
   до тела: выполнился этот — значит скрипты доступны, и показывать окно
   «как карточку» незачем. Без скриптов не выполнится и он, отметки не будет,
   и окно останется на месте.
   ========================================================================== */

(function () {
    'use strict';

    document.documentElement.setAttribute('data-js', '');
}());
