/* ==========================================================================
   Установка темы до первой отрисовки.

   Подключается в шапке без defer: скрипт должен выполниться раньше, чем браузер
   нарисует страницу. Иначе панель мигнёт светлой и нарисуется светлой — а
   тёмные значения живут в правиле [data-theme="dark"], и пока атрибута нет,
   действуют светлые.

   Отдельный файл, а не код в разметке: политика безопасности отдаётся с
   script-src 'self', и инлайн-скрипт был бы просто заблокирован — страница
   выглядела бы рабочей, а тема молча не переключалась бы.

   Здесь же ставится отметка data-js: скрипт в шапке выполняется до разбора
   тела, и этого достаточно, чтобы окна не показывались как обычные блоки.

   При запрете хранилища остаётся тёмная тема: в разметке атрибут data-theme
   уже стоит, скрипт лишь уточняет его сохранённым выбором.
   ========================================================================== */

(function () {
    'use strict';

    var theme = 'dark';

    try {
        theme = window.localStorage.getItem('myedu-theme') || 'dark';
    } catch (e) {
        // При запрете хранилища остаётся то, что стоит в разметке.
    }

    document.documentElement.setAttribute('data-theme', theme);

    /*
     * Отметка «скрипты работают» — тоже здесь, а не в том скрипте, который
     * первым до неё дотянется.
     *
     * Пока отметки нет, `html:not([data-js]) [data-modal]` показывает окно
     * обычным блоком — так страница остаётся рабочей без JavaScript. Но окно
     * лежит в разметке, и до `modal-open.js` оно успевает раздуть документ:
     * страница с формой задания становится почти на тысячу пикселей выше,
     * браузер уводит прокрутку к раздутому блоку, а скрипт окно закрывает и
     * документ сжимается. Прокрутка остаётся внизу, и закрытие окна выглядит
     * так, будто страницу утащило в самый конец.
     *
     * Отметка ставится в шапке именно потому, что здесь скрипт ещё гарантированно
     * до тела: выполнился этот — значит скрипты доступны, и показывать окно
     * «как карточку» незачем. Без скриптов не выполнится и он, отметки не будет,
     * и окно останется на месте.
     */
    document.documentElement.setAttribute('data-js', '');
}());