/* ==========================================================================
   Уборка тестовой попытки при закрытии вкладки.

   Тестовое прохождение работы (решение владельца от 24.10.2026, задача 6)
   существует только, пока открыта вкладка с ним: результаты пробной сдачи
   не должны копиться в базе, попадать в статистику и в журнал.

   `pagehide` — единственное событие, которое браузер гарантирует при
   закрытии вкладки, переключении на другую вкладку и даже при сворачивании
   вкладки на телефоне. `navigator.sendBeacon` отправляет последний пакет,
   который браузер успевает отослать уже после выгрузки страницы: обычный
   fetch на этом месте просто не долетает.

   Content-Type обязателен: без него браузер помечает пакет как text/plain,
   и PHP не кладёт его в $_POST — сервер не находит ни токена, ни номера
   попытки и молча не убирает ничего.

   Страховка: даже если пакет не ушёл (закрытие без сети, запрет beacon),
   попытка убирается при следующем входе в тестовое прохождение — база не
   копит пробные результаты в любом случае.

   Подключается только на страницах тестового прохождения: оболочка ставит
   meta только тогда, когда в сессии есть метка тестовой попытки.
   ========================================================================== */

(function () {
    'use strict';

    var meta = document.querySelector('meta[name="trial-cleanup"]');

    if (!meta || !navigator.sendBeacon) {
        return;
    }

    var url = meta.getAttribute('content') || '';
    var attempt = meta.getAttribute('data-attempt') || '';
    var csrf = document.querySelector('meta[name="csrf-token"]');

    if (url === '' || attempt === '' || !csrf) {
        return;
    }

    document.addEventListener('pagehide', function () {
        var body = new Blob(
            [
                '_token=' + encodeURIComponent(csrf.getAttribute('content') || ''),
                '&attempt=' + encodeURIComponent(attempt),
            ].join(''),
            { type: 'application/x-www-form-urlencoded' }
        );

        navigator.sendBeacon(url, body);
    });
}());
