/* ==========================================================================
   Кнопка печати на листе с логинами.

   Обработчик живёт здесь, а не в атрибуте onclick: инлайн-обработчики
   запрещены Content-Security-Policy, а ослаблять политику ради одной кнопки
   означало бы не ставить её вовсе.
   ========================================================================== */

(function () {
    'use strict';

    document.querySelectorAll('[data-print]').forEach(function (button) {
        button.addEventListener('click', function () {
            window.print();
        });
    });
}());