/* ==========================================================================
   Переключатель плагина.

   Переключатель в форме отправляет форму сам — по событию change, без
   кнопки. Кнопка в разметке есть и видна намеренно: без скриптов это
   единственный способ включить или выключить плагин, и убрать её оттуда
   значило бы оставить управление плагинами только тем, у кого включён
   JavaScript. Скрипт наоборот убирает кнопку и отправляет форму сразу.

   Отправка обычная, тем же POST, что и без скриптов: состояние плагина
   меняет сервер, а не страница. После ответа сервер отдаёт список заново,
   поэтому переключатель на экране — это состояние, прочитанное с сервера,
   а не нарисованная надежда.

   На страницах без такой формы скрипт не делает ничего.
   ========================================================================== */

function bind(form) {
  // Флажок ищется по типу, а не по имени класса: класс на самом флажке нужен
  // был бы только ради этого поиска, а лишний класс в разметке — это лишний
  // класс, о котором потом кто-то спросит, зачем он.
  const toggle = form.querySelector('input[type="checkbox"]');
  const save = form.querySelector('.plugin-switch-save');

  if (!toggle) {
    return;
  }

  if (save) {
    save.hidden = true;
  }

  form.addEventListener('submit', (event) => {
    // Форма уходит сама и без этого, но по событию change страница успевает
    // уехать раньше, чем браузер дойдёт до конца обработчика: после отправки
    // перерисовывать уже нечего, а до неё — есть что показать.
    if (event.submitter && event.submitter !== save) {
      return;
    }

    event.preventDefault();
    form.submit();
  });

  toggle.addEventListener('change', () => {
    form.submit();
  });
}

function init() {
  document.querySelectorAll('form.plugin-switch').forEach(bind);
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', init);
} else {
  init();
}