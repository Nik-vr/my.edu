/* ==========================================================================
   Автопечать листа с логинами и паролями.

   Лист открывается в новом окне по нажатию «Печать паролей» и сразу уходит на
   печать: отдельное нажатие «Печать» после открытия — лишний шаг, который
   человек забывает, и тогда лист так и остаётся на экране.

   Команда отправляется после загрузки, а не сразу: иначе пришлось бы ждать
   шрифты и вёрстку, и на печать попал бы лист до того, как он появился.

   Кнопка печати на листе остаётся: она нужна, если окно печати закрыли или
   браузер спросил подтверждение — повторить можно одним нажатием, и для этого
   не нужно никуда возвращаться.

   Если скрипт не доехал, лист просто откроется: печать вызывается кнопкой
   и сочетанием клавиш, то есть и без него.

   Живёт в файле, а не в разметке: политика безопасности отдаётся с
   script-src 'self', и код прямо в странице был бы заблокирован.
   ========================================================================== */

(function () {
    'use strict';

    function start() {
        var button = document.querySelector('[data-print]');

        if (button) {
            button.addEventListener('click', function () {
                window.print();
            });
        }

        window.print();
    }

    if (document.readyState === 'complete') {
        start();
    } else {
        window.addEventListener('load', start);
    }
}());