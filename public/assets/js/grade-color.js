/* ==========================================================================
   Собственный цвет оценки на страницах.

   Четыре палитры (зелёный, синий, жёлтый, красный) красятся CSS-классами и
   работают без скриптов. Но автор может выбрать в палитре браузера любую
   другую краску (решение владельца от 24.10.2026, задача 4), и такого цвета
   в CSS нет: он приходит атрибутом data-grade-color="#rrggbb" и применяется
   здесь.

   Значение проверяется регуляркой, хотя сервер уже привёл его к `#rrggbb`
   при сохранении: атрибут читает любой скрипт на странице, и полагаться на
   чужую валидацию не стоит — проверка стоит одну строку.

   Инлайнового стиля в самой разметке при этом нет: style= в шаблонах
   запрещён правилами интерфейса (tests/run_ui_rules_tests.php), а цвет
   накладывает скрипт после загрузки — для четырёх привычных цветов ничего
   не требуется, и страница без скриптов остаётся покрашенной.

   Подключается в оболочке панели: там и результат ученика, и шкала в
   редакторе работы.
   ========================================================================== */

(function () {
    'use strict';

    var HEX = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i;

    document.querySelectorAll('[data-grade-color]').forEach(function (node) {
        var value = node.getAttribute('data-grade-color') || '';

        if (HEX.test(value)) {
            node.style.color = value;
        }
    });
}());
