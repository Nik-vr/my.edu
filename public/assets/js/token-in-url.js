/*
 * Токен не должен оставаться в адресе.
 *
 * Два адреса приходят с токеном в строке запроса: работа по ссылке (`?t=…`) и
 * форма нового пароля по ссылке из письма (`?token=…`). В обоих случаях
 * убрать его из ссылки нельзя — иначе её не открыть, а это основной способ.
 *
 * Остальное можно: адрес с токеном копируется, попадает в историю браузера и
 * уезжает в `Referer` при переходе куда угодно, а токен одноразовый и открывает
 * чужую попытку или меняет чужой пароль.
 *
 * После загрузки страницы токен убирается из адресной строки через
 * `replaceState` — запись истории подменяется, а не добавляется, поэтому
 * кнопка «назад» не вернёт адрес с токеном и в скопированной ссылки его уже
 * не будет. Всё остальное делает сервер: страница отрисована и токен проверен,
 * а форма сброса кладёт его в скрытое поле, так что нажатие кнопки работает
 * и после очистки адреса.
 *
 * Если в адресе нет токена, скрипт не делает ничего.
 */
(function () {
    'use strict';

    if (!window.history || typeof window.history.replaceState !== 'function') {
        return;
    }

    var current = window.location.search;

    if (!current) {
        return;
    }

    var params = new URLSearchParams(current);
    var touched = false;

    ['t', 'token'].forEach(function (name) {
        if (params.has(name)) {
            params.delete(name);
            touched = true;
        }
    });

    if (!touched) {
        return;
    }

    /*
     * Пересобираются только те параметры, что остаются: всё, кроме токена, в
     * том числе возвращается на место и в том же порядке. Иначе страница,
     * открытая с дополнительным параметром, потеряла бы его.
     */
    var rest = params.toString();
    var clean = window.location.pathname + (rest ? '?' + rest : '') + window.location.hash;

    window.history.replaceState(window.history.state, document.title, clean);
})();