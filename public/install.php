<?php

declare(strict_types=1);

/**
 * Установка базы данных через браузер — для хостингов без SSH и без импорта
 * из phpMyAdmin.
 *
 * Обычный путь: импортировать database/schema.sql через панель управления.
 * Этот файл нужен там, где такого импорта нет.
 *
 * ------------------------------------------------------------------
 *  ПОЧЕМУ ЗДЕСЬ НЕ СТРАШНО, ЧТО ФАЙЛ ОТКРЫТ ДЛЯ ВСЕХ
 * ------------------------------------------------------------------
 *
 * Установщик отказывается работать, если в базе есть хоть одна таблица.
 * То есть он не может ничего испортить: там, где есть данные, он просто
 * не сделает ничего. А на пустой базе создать таблицы безопасно — данных
 * там ещё нет.
 *
 * Второй замок — ключ установки. Пока он не задан в
 * `config/config.local.php`, файл отвечает 403 любому запросу, включая
 * совсем без параметров. Раньше этого не было: страницу мог открыть кто
 * угодно, и она показывала имена таблиц базы и текст ошибок от сервера
 * MySQL — то есть имя базы, логин и путь к хостингу.
 *
 * Текст ошибок от сервера базы при `app.debug = false` наружу не
 * выводится: он уходит в журнал PHP, а на странице остаётся объяснение,
 * что делать.
 *
 * После успешной установки файл удаляет сам себя. Если удалить не вышло,
 * он скажет об этом и больше ничего делать не станет: повторный запуск всё
 * равно будет отклонён.
 *
 * ------------------------------------------------------------------
 *  ЧТО ОН ДЕЛАЕТ
 * ------------------------------------------------------------------
 *
 * 1. Сверяет ключ установки с секретом из конфигурации.
 * 2. Проверяет подключение к базе из config/config.local.php.
 * 3. Убеждается, что база пуста.
 * 4. Выполняет database/schema.sql — это снимок схемы целиком, поэтому
 *    отдельные миграции после импорта не нужны и не запускаются.
 * 5. Удаляет сам себя, чтобы установку нельзя было повторить случайно.
 *
 * Файл разбирает SQL с учётом кавычек и комментариев: в schema.sql есть
 * `COMMENT '...; ...'`, и простое деление по точке с запятой разорвало бы
 * такие строки.
 */

use MyEdu\Core\Config;
use MyEdu\Core\Database;
use MyEdu\Core\SchemaMigrator;

$rootDir = dirname(__DIR__);

require $rootDir . '/src/Core/Autoloader.php';

MyEdu\Core\Autoloader::create($rootDir);

/** Ответ странице и конец работы. */
function finish(string $title, string $body, string $status = 'ok'): never
{
    echo '<!DOCTYPE html><html lang="ru"><head><meta charset="utf-8">'
        . '<meta name="viewport" content="width=device-width, initial-scale=1">'
        . '<title>Установка базы — ' . htmlspecialchars($title, ENT_QUOTES) . '</title>'
        . '<style>body{font:16px/1.6 system-ui,sans-serif;margin:40px auto;max-width:720px;padding:0 20px}'
        . 'code{background:#f2f2f2;padding:2px 5px;border-radius:3px}'
        . '.ok{border-left:4px solid #2e7d32;padding-left:14px}'
        . '.bad{border-left:4px solid #c62828;padding-left:14px}'
        . '.warn{border-left:4px solid #ef6c00;padding-left:14px}</style>'
        . '</head><body><h1>' . htmlspecialchars($title, ENT_QUOTES) . '</h1>'
        . '<div class="' . $status . '">' . $body . '</div></body></html>';

    exit;
}

/*
 * Разбор SQL-файла — общий с ядром, в SchemaMigrator::splitStatements().
 *
 * Свой разборщик здесь стоял раньше и разбирал файл иначе, чем мигратор:
 * не понимал экранированную кавычку внутри строки и метку порядка байтов
 * UTF-8. Один и тот же файл, загруженный одним путём и другим, давал бы
 * разный результат — а отличить это можно было бы только по сообщению
 * об ошибке SQL из середины файла.
 */

$config = Config::load($rootDir . '/config');
$database = $config->array('database');
$debug = $config->bool('app.debug', false);

// ------------------------------------------------------------------- ключ

/*
 * Ключ установки сверяется с секретом, а не просто спрашивается.
 *
 * Пока ключ не задан, страница закрыта для всех — включая запрос вообще без
 * параметра. Пустая строка секретом не считается: забытый `key => ''` открыл
 * бы установку любому, кто пришлёт пустое значение.
 */
$expectedKey = (string) $config->string('install.key', '');
$givenKey = (string) ($_GET['key'] ?? '');

if ($expectedKey === '' || $givenKey === '' || !hash_equals($expectedKey, $givenKey)) {
    http_response_code(403);
    header('Content-Type: text/plain; charset=utf-8');

    exit(
        "Нужен ключ установки.\n"
        . "Задайте его в config/config.local.php:\n"
        . "    'install' => ['key' => 'длинный случайный набор знаков'],\n"
        . "и откройте адрес вида install.php?key=ваш_ключ\n"
        . "После установки удалите и ключ, и сам файл.\n"
    );
}

/**
 * Текст ошибки от сервера базы.
 *
 * Наружу он выводится только при включённой отладке: в тексте PDO есть имя
 * базы, логин и путь к хостингу, а страница установки доступна из интернета по
 * адресу, который владелец обычно открывает один раз и забывает удалить.
 */
function databaseError(Throwable $e, bool $debug): string
{
    if ($debug) {
        return '<p>' . htmlspecialchars($e->getMessage(), ENT_QUOTES) . '</p>';
    }

    return '<p>Подробности ошибки записаны в журнал PHP на сервере. '
        . 'Чтобы увидеть их на этой странице, включите <code>app.debug</code> '
        . 'в <code>config/config.local.php</code> — и выключите обратно сразу '
        . 'после разбора.</p>';
}

// --------------------------------------------------------------- подключение

try {
    $db = new Database($database);
} catch (Throwable $e) {
    finish(
        'Не удалось подключиться к базе',
        databaseError($e, $debug)
        . '<p>Проверьте значения <code>database</code> в <code>config/config.local.php</code>: '
        . 'адрес, порт, имя базы, логин и пароль берутся из панели управления хостингом.</p>',
        'bad'
    );
}

// --------------------------------------------------------------- база должна быть пуста

$existing = $db->all('SHOW TABLES');

if ($existing !== []) {
    // Имена таблиц не показываются: они рассказывают постороннему, какая у
    // владельца база и что в ней есть. Числа достаточно, чтобы понять, что
    // установка уже прошла.
    finish(
        'Установка не выполняется: база не пуста',
        '<p>В базе уже есть таблицы, поэтому установщик ничего не трогает. '
        . 'Это защита: он не может испортить данные.</p>'
        . '<p>Найдено таблиц: <strong>' . count($existing) . '</strong>.</p>'
        . '<p>Если база уже установлена, всё в порядке — просто удалите этот файл.</p>',
        'warn'
    );
}

// --------------------------------------------------------------- импорт схемы

$schemaFile = $rootDir . '/database/schema.sql';

if (!is_file($schemaFile)) {
    finish('Файл схемы не найден', '<p>Ожидался <code>database/schema.sql</code>.</p>', 'bad');
}

$sql = (string) file_get_contents($schemaFile);
$statements = SchemaMigrator::splitStatements($sql);
$pdo = $db->pdo();
$done = 0;

try {
    foreach ($statements as $statement) {
        $pdo->exec($statement);
        $done++;
    }
} catch (Throwable $e) {
    finish(
        'Импорт прерван',
        '<p>Выполнено запросов: <strong>' . $done . '</strong> из ' . count($statements) . '.</p>'
        . databaseError($e, $debug)
        . '<p>База осталась в промежуточном состоянии. Удалите её в панели и '
        . 'установите заново либо импортируйте схему вручную.</p>',
        'bad'
    );
}

/*
 * Журнал миграций.
 *
 * Отмечать нечего и незачем: база собрана импортом снимка схемы, а не набором
 * миграций, и файлов миграций на диске сейчас нет. Отметки понадобятся, когда
 * появится первая новая миграция — до того момента журнал остаётся пустым, и
 * это правильное состояние, а не потеря.
 *
 * Таблица `schema_migrations` при этом создаётся тем же импортом: она есть в
 * `schema.sql`.
 */

// --------------------------------------------------------------- удаление файла

$removed = false;

if (@unlink(__FILE__)) {
    $removed = true;
}

// --------------------------------------------------------------- отчёт

finish(
    'База установлена',
    '<p>Выполнено запросов: <strong>' . $done . '</strong>.</p>'
    . '<p>Схема собрана из снимка <code>database/schema.sql</code> целиком: '
    . 'применять миграции не нужно, их на диске нет.</p>'
    . '<p class="warn"><strong>Удалите этот файл с сервера прямо сейчас.</strong><br>'
    . ($removed
        ? 'Файл удалён автоматически.'
        : 'Автоматически удалить не удалось — удалите <code>install.php</code> из каталога <code>public/</code> вручную.')
    . '</p>'
    . '<p>И удалите ключ установки из <code>config/config.local.php</code>: он больше не нужен, '
    . 'а страница без него всё равно не откроется.</p>'
    . '<p>Дальше:</p>'
    . '<ol>'
    . '<li>Откройте сайт: первый зарегистрировавшийся станет владельцем.</li>'
    . '<li>Задайте <code>app.url</code> в <code>config/config.local.php</code>, '
    . 'чтобы ссылки в письмах были верными.</li>'
    . '<li>Проверьте отправку писем: драйвер <code>mail.driver</code> должен быть '
    . '<code>mail</code> или <code>smtp</code>, а не <code>log</code>.</li>'
    . '</ol>'
);