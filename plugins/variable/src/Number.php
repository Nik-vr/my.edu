<?php

declare(strict_types=1);

namespace MyEduPlugin\Variable;

/**
 * Разбор и печать чисел.
 *
 * Правила заданы здесь, а не взяты из соседнего плагина: то, как плагин понимает
 * число в ответе ученика, — это его собственное решение, и тянуть ради этого
 * чужой тип вопроса значило бы связать два плагина, которые не должны знать
 * друг о друге.
 */
final class Number
{
 /**
 * Число из строки, как его вводит человек.
 *
 * Принимаются «12», «12,5», «−3» и « 4 ». Ноль — это число, а «нуль» и
 * пустая строка — нет: отсутствие ответа и ответ «0» различать важно, иначе
 * незаполненное поле сочлось бы решённым.
 *
 * @return float|null null — если это не записано как число
 */
 public static function parse(string $text): ?float
 {
 $normalized = trim(str_replace(["\u{00A0}", "\u{202F}"], ' ', $text));
 $normalized = (string) preg_replace('/\s+/u', ' ', $normalized);

 /*
 * Минус приходит двумя знаками: в обычной клавиатуре это дефис, а при
 * копировании из документа — типографский «−». Оба должны значить одно и
 * то же, иначе ответ «−3» из мобильной клавиатуры не распознался бы и
 * ученик получил бы ноль за верный ответ.
 */
 $normalized = str_replace(["\u{2212}", "\u{2013}", "\u{2014}"], '-', $normalized);

 // Ведущий мусор («≈», «примерно») на число не влияет и отбрасывается.
 $normalized = (string) preg_replace('/^[^\-+0-9]+/u', '', $normalized);

 // Всё, что осталось, должно быть числом и, возможно, единицей измерения.
 if (preg_match('/^([-+]?\d+(?:[.,]\d+)?)\s*[^\d]{0,24}$/u', $normalized, $matches) !== 1) {
 return null;
 }

 $value = str_replace(',', '.', $matches[1]);

 return is_numeric($value) ? (float) $value : null;
 }

 /**
 * Число для показа в условии и в разборе.
 *
 * Округление до шести знаков обязательно: без него (0.1 + 0.2) попадало бы
 * в текст задачи как 0,30000000000000004, и это выглядело бы ошибкой
 * плагина, а не арифметики.
 */
 public static function format(float $value): string
 {
 $rounded = round($value, 6);

 if (abs($rounded - round($rounded)) < 1e-9) {
 return (string) (int) round($rounded);
 }

 return rtrim(rtrim(number_format($rounded, 6, '.', ''), '0'), '.');
 }
}