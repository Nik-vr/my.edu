<?php

declare(strict_types=1);

/**
 * Форма редактора задания.
 *
 * Отдельный файл, потому что рисуется в двух местах: на своей странице и
 * встроенной карточкой в редакторе работы. Копия формы означала бы две
 * версии правил типа вопроса, и они разошлись бы при первой правке.
 *
 * Скрипты в конце — тоже здесь, а не в обёртке: при встройке в редактор
 * работы обёртки этой страницы нет, и без них не работал бы ни выбор полей,
 * ни визуальный редактор.
 *
 * Ожидает:
 * $view, $task, $form, $backUrl, $prefix, $assignmentPublished
 *
 * @var \MyEdu\Core\View $view
 * @var array<string,mixed> $task
 * @var array<string,mixed> $form
 * @var string $backUrl
 * @var string $prefix
 * @var bool $assignmentPublished опубликована ли работа, в которой лежит задание
 */
$taskId = (int) $task['id'];
?>
<div class="card">
  <?php /*
   Предупреждение об опубликованной работе показывает ядро — значком в шапке
   окна, слева от номера задания. Здесь оно было бы второй копией того же текста
   в другом месте: встроенный редактор и так открывается поверх доски, где
   значок уже стоит.
   */ ?>

<?php /*
 data-fixed-type — подсказка скрипту, какой блок полей показать.
 Селектора типа здесь нет: тип выбран при добавлении и не меняется.
*/ ?>
 <form method="post" action="<?= $view->e($view->url($prefix . '/task/' . $taskId)) ?>"
 data-ajax-save
 data-fixed-type="<?= $view->e($form['type']) ?>">
 <?= $view->raw($view->csrfField()) ?>
 <?= $view->raw($ui->hidden('action', 'save_task')) ?>
 <?= $view->raw($ui->hidden('question_id', (int) $form['id'])) ?>
 <?= $view->raw($ui->hidden('type', $form['type'])) ?>
 <?= $view->raw($ui->hidden('back', $backUrl)) ?><?php /*
 back в форме, а не только в адресе: без него сохранение отправляло бы
 автора обратно на редактор задания вместо списка заданий работы.

 require ниже обязан остаться внутри <?php ?>: если закрыть режим
 перед ним, строка уйдёт в разметку как текст, и полей вопроса на
 странице просто не будет.
*/ ?>

 <?php require __DIR__ . '/_question_fields.php'; ?>

 <?php /*
 Одна кнопка сохранения. Раньше рядом с «Сохранить задание» стояла
 «Опубликовать задание», и она решала не то, зачем открыт редактор:
 отдельная страница задания нужна была, чтобы довести её до ума, и
 публикация была последним шагом именно там.

 Теперь задание живёт в списке позиций работы, публикуется работа
 целиком последним шагом мастера, а в редакторе одно действие, которое
 что-то меняет, — сохранить.

 «Отмена» рядом с ним — закрыть без сохранения. Раньше закрыть редактор
 можно было только ссылкой в шапке карточки, до всех полей, и человек
 вправе был не заметить её в длинной форме. Ссылка, а не submit: форма
 на неё не уходит никогда, поэтому потерять правку нельзя даже там, где
 скрипты запрещены, — скрипт лишь спрашивает подтверждение.
 */ ?>
 <div class="page-actions">
 <?= $view->raw($ui->button('Сохранить задание', ['size' => 'btn-lg'])) ?>

 <a class="btn btn-ghost btn-lg"
 href="<?= $view->e($view->url($closeUrl !== '' ? $closeUrl : $backUrl)) ?>"
 data-editor-cancel
 data-editor-cancel-message="Изменения не будут сохранены. Закрыть редактор?">Отмена</a>
 </div>
</form>
</div>

<?php /*
 Скрипты редактора подключает ядро, а не плагин: библиотека и обработчики
 одни и те же для всех систем проверки, и подключать их в каждом шаблоне
 плагина — значит забыть в одном из них и получить страницу, на которой
 редактор не отвечает, а кнопки вариантов не работают.
*/ ?>
<?= $view->raw($ui->editorScripts()) ?>
