<?php

declare(strict_types=1);

/**
 * Настройки задания: вкладка «Настройки» редактора.
 *
 * Здесь то, что к самому вопросу отношения не имеет: обязателен ли ответ,
 * что показать в разборе и перемешивать ли варианты.
 *
 * Перемешивание вариантов — настройка всего задания, а не вопроса: варианты
 * переставляются в одном задании целиком. Показывается она только у типов, у
 * которых варианты вообще есть: у текстового ответа и у числа переставлять
 * нечего, и галочка там была бы обещанием, которое нельзя выполнить.
 *
 * Ожидает:
 * $view, $ui, $form
 *
 * @var \MyEdu\Core\View $view
 * @var \MyEdu\Ui\Ui $ui
 * @var array<string,mixed> $form
 */

$hasOptions = !empty($form['hasOptions']);

/*
 * Сколько вариантов показывать — у видов с выбором ответа.
 *
 * У «Соответствие» выбор устроен иначе: там выбирают пары, поэтому лимит
 * действует на правую колонку, а левая остаётся полной — см.
 * MatchingType::payload(). Отсекаются только отвлекающие варианты, и
 * всегда показываются верные партнёры видимых левых элементов, так что
 * неразрешимых пар не получается. У текстового ответа и числа переставлять
 * или урезать нечего, и поле там не показывается.
 */
$hasRandomCount = in_array((string) ($form['type'] ?? ''), ['single_choice', 'multiple_choice', 'matching'], true);
$config = (array) ($form['config'] ?? []);
?>

<div class="card">
 <h2 class="card-title">Настройки</h2>

 <?= $view->raw($ui->checkbox('is_required', [
     'label'   => 'Ответ обязателен',
     'checked' => (bool) $form['required'],
     'help'    => 'Без ответа работа не засчитывается: ученик должен ответить на вопрос.',
 ])) ?>

 <?= $view->raw($ui->textarea('explanation', [
     'label'       => 'Пояснение после проверки',
     'value'       => $form['explanation'],
     'rows'        => 3,
     'placeholder' => 'Показывается в разборе: почему такой ответ верный',
 ])) ?>

 <?php if ($hasRandomCount): ?>
 <?php /*
 Вариантов у вопроса бывает больше, чем показывается: лишние только мешают.
 Состав и порядок выбора закреплены за попыткой, так что при обновлении страницы
 ученик видит те же варианты.
 */ ?>
 <?= $view->raw($ui->field('random_options', [
     'label'       => 'Выбрать N случайных вариантов ответа',
     'type'        => 'number',
     'value'       => (int) ($config['random_options'] ?? 0),
     'min'         => '0',
     'max'         => '99',
     'step'        => '1',
     'size'        => 5,
     'help'        => 'Пусто или ноль — показываются все варианты. Отмеченные как «Обязательно '
         . 'показывать» показываются в любом случае, и правильный ответ — тоже.',
 ])) ?>
 <?php endif; ?>

 <?php if ($hasOptions): ?>
 <?= $view->raw($ui->checkbox('shuffle_options', [
     'label'   => 'Перемешать варианты ответа случайным образом',
     'checked' => (bool) ($form['shuffleOptions'] ?? false),
     'help'    => 'У каждого ученика варианты будут в своём порядке. Порядок закреплён за попыткой: '
         . 'вернувшись к заданию, ученик увидит те же варианты, что и в первый раз.',
 ])) ?>
 <?php endif; ?>
</div>
